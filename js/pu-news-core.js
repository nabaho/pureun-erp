  /* 'YYYY-MM-DD' → UTC 자정. 시간대에 휘둘리지 않으려고 UTC 로만 셈한다. */
  function _날(s) {
    var d = new Date(String(s == null ? '' : s).slice(0, 10) + 'T00:00:00Z');
    return isNaN(d) ? null : d;
  }
  function _글(d) { return d.toISOString().slice(0, 10); }

  /* 그 날 이전(그날 포함)의 가장 가까운 일요일 */
