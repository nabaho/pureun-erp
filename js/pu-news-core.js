  /* 한 곳이 «어디까지 갔나» — 네 가지로만 말한다.
     ★ 왜 이 판단이 따로 필요한가 —
       나간 편지는 대기열에서 «지워진다»(서버가 보낸 뒤 그 줄을 없앤다).
       그래서 「대기열에 없다」는 것만으로는 «나갔다»인지 «애초에 안 걸렸다»인지
       알 수 없다. 걸 때 찍어 둔 «보냄표»가 그 둘을 가른다.
     ⚠ 모르는 것을 「나감」이라고 하지 않는다 — 안 나간 것을 나갔다고 하면
       대표가 그 곳에 다시 안 보낸다. */
  function 보낸상태(x) {
    var r = x || {};
    if (!r.보냄표) return '안걺';
    if (r.오류) return '실패';
    var s = String(r.나갔나 || '');
    if (s === 'error') return '실패';
    if (s === 'waiting' || s === 'sending') return '대기';
    return '나감';                     /* 걸었고, 대기열에 없다 = 나갔다 */
  }

  /* 보낸 결과 한 눈에 — 세어서 띠에 건다.
     ⚠ 「열람」은 «나간 것» 가운데 센다. 안 나간 것까지 분모에 넣으면
       열람률이 실제보다 낮게 보이고, 그 숫자를 보고 명단을 자르게 된다. */
  function 결과셈(줄들) {
    var s = { 전체: 0, 나감: 0, 대기: 0, 실패: 0, 안걺: 0,
              열람: 0, 클릭: 0, 반송: 0, 자동회신: 0 };
    (줄들 || []).forEach(function (x) {
      s.전체++;
      var 상 = 보낸상태(x);
      s[상] = (s[상] || 0) + 1;
      if (상 === '나감') {
        if (x.열람) s.열람++;
        if (x.클릭) s.클릭++;
      }
      var g = x.메일함 && x.메일함.갈래;
      if (g === '반송') s.반송++;
      else if (g === '자동회신') s.자동회신++;
    });
    return s;
  }

  function 광고표기필요한가(범위) {
    return String(범위) !== '자문중';
  }

  function 제목짓기(회차한벌, 범위) {
    var t = (회차한벌 && 회차한벌.제목) || '푸른노무법인 주간뉴스레터 입니다.';
    return 광고표기필요한가(범위) ? '(광고) ' + t : t;
  }

