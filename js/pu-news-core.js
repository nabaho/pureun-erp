  function 미열람판단(기록, 회차들, 규칙) {
    var R = 규칙 || 미열람규칙;
    var 최근 = Math.max(1, Number(R.최근) || 5);
    var 넘으면 = Math.max(1, Number(R.넘으면) || 3);
    var 목록 = Array.isArray(회차들) ? 회차들 : [];   /* 새것부터 온다 */
    var 기 = 기록 && typeof 기록 === 'object' ? 기록 : {};

    var 후보 = [], 반송 = [];
    Object.keys(기).forEach(function (e) {
      var 표 = 기[e] || {};

      /* 반송이 한 번이라도 있으면 그것으로 끝 — 주소가 죽었다 */
      var 반송회차 = null;
      목록.forEach(function (k) { if (!반송회차 && 표[k] && 표[k].반송) 반송회차 = k; });
      if (반송회차) { 반송.push({ email: e, 회차: 반송회차 }); return; }

      /* «보낸» 회차만 새것부터 최근 개까지 */
      var 본것 = [];
      for (var i = 0; i < 목록.length && 본것.length < 최근; i++) {
        var m = 표[목록[i]];
        if (m && m.보냄) 본것.push(m);
      }
      if (!본것.length) return;

      var 안읽은수 = 본것.filter(function (m) { return !m.열람 && !m.클릭; }).length;
      if (안읽은수 >= 넘으면) {
        후보.push({ email: e, 안읽은수: 안읽은수, 본회차수: 본것.length });
      }
    });

    /* 많이 안 읽은 곳부터 — 화면에서 위에 보이게 */
    후보.sort(function (a, b) { return b.안읽은수 - a.안읽은수; });
    return { 후보: 후보, 반송: 반송, 규칙: { 최근: 최근, 넘으면: 넘으면 } };
  }

