  /* 파일 이름에서 «무슨 파일인지» — 「…안내(홈페이지 게시).pdf」 → pdf */
  function 확장자뽑기(이름) {
    var m = /\.([a-z0-9]{2,5})(?:\?|$)/i.exec(String(이름 == null ? '' : 이름));
    return m ? m[1].toLowerCase() : '';
  }

  function 노무사회줄(자료) {
    var x = 자료 || {};
    var 제목 = String(x.제목 || '').trim();
    if (!제목) return null;                       /* 제목 없는 것은 편지에 못 싣는다 */

    /* ★★ 첨부가 있으면 «자료»다 (2026-09-06 대표 화면에서 드러났다)
       ═══════════════════════════════════════════════════════════════════════
       노무사회에서 받아 둔 것에는 «기관·날짜·첨부(이름·주소·크기)»가 이미 다 있고,
       파일도 이미 우리 창고에 들어와 있다. 그런데 담을 때 그것을 «통째로 버리고»
       기사 한 줄로 만들고 있었다. 그래서 대표께서 노무사회 자료를 담으셔도
       고용·노동정책이 «점 찍힌 줄»로만 나왔다 — 표지도 내려받기도 없이.
       ⚠ 첨부가 없으면 예전대로 기사다. 내려받을 것이 없으면 자료가 아니다. */
    var 첨 = (Array.isArray(x.첨부) ? x.첨부 : [])
      .filter(function (f) { return f && f.주소; })[0];
    if (첨) {
      var 것 = 자료다듬기({
        제목: 제목,
        발행처: String(x.기관 || '').trim() || '공인노무사회',
        발행일: String(x.날짜 || ''),
        파일: String(첨.주소 || ''),
        파일이름: String(첨.이름 || ''),
        확장자: 확장자뽑기(첨.이름),
        파일크기: Number(첨.크기) || 0,
        파일자리: String(첨.자리 || ''),
        링크: String(x.주소 || '')
      });
      것.sid = String(x.sid || '');                /* 두 번 담지 않으려고 들고 있는다 */
      return 것;
    }

    return {
      갈래: '기사',                                /* 서식이 기사와 같은 꼴로 그린다 */
      제목: 제목,
      링크: String(x.주소 || ''),
      언론사: '공인노무사회',
      기관: String(x.기관 || ''),                  /* 국가데이터처·고용노동부 … */
      sid: String(x.sid || '')
    };
  }

