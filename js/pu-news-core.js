  var 발송기_분마다 = 15;   /* functions/mail-bulk.js DRAIN_EVERY_MIN 과 같아야 한다 */
  var 발송기_한줌 = 20;     /* functions/mail-bulk.js DRAIN_BATCH 와 같아야 한다 */

  function 보낼시간(곳수, 간격초) {
    var n = Math.max(0, Number(곳수) || 0);
    var 간격분 = Math.round((n * (Number(간격초) || 0)) / 60);
    var 발송분 = Math.ceil(n / 발송기_한줌) * 발송기_분마다;
    var 분 = Math.max(1, 간격분, 발송분);
    if (분 < 60) return '약 ' + 분 + '분';
    var h = Math.floor(분 / 60), m = 분 % 60;
    return '약 ' + h + '시간' + (m ? ' ' + m + '분' : '');
  }

