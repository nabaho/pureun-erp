/* fund_forms.js 전수 개인정보·실데이터 스캔.
   서식 템플릿은 «어느 기금이 실제로 낸 서류»를 변환한 것이라, 사람 이름·집주소·
   계좌번호가 그대로 딸려 온다. fund.html·fund_forms.js 는 인터넷에 공개 배포되므로
   그대로 두면 남의 개인정보가 주소만 알면 읽힌다.

   ⚠ 예전에는 이 검사가 «다른 폴더»를 보고 있었다(C:/Users/fair0/Documents/pureunall).
     그래서 깨끗하다고 나오는 동안 저장소의 서식에는 실명·집주소·계좌번호가 남아 있었다.
     이제 «이 저장소»를 본다 — 경로를 박아 두지 않는다.

   실행: node fund-erp/tools/pii_scan.js */
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const FORMS = path.join(ROOT, 'fund_forms.js');
if (!fs.existsSync(FORMS)) { console.log('✗ fund_forms.js 를 못 찾음: ' + FORMS); process.exit(1); }
global.window = {};
(0, eval)(fs.readFileSync(FORMS, 'utf8'));
const F = global.window.HWP_FORMS || {};

const PATTERNS = [
  ['전화번호', /\b0\d{1,2}[-)]\s?\d{3,4}-\d{4}\b/g],
  ['휴대폰', /\b01[016789][-)]?\s?\d{3,4}-?\d{4}\b/g],
  ['주민번호', /\b\d{6}\s*-\s*[1-4]\d{6}\b/g],
  ['상세주소', /(서울|경기|인천|부산|대구|광주|대전|울산|세종|강원|충북|충남|전북|전남|경북|경남|제주)(특별시|광역시|도)?\s?[가-힣]{1,10}(시|군|구)\s?[^<{]{4,50}/g],
  ['사업자번호', /(?<![\d-])\d{3}-\d{2}-\d{5}(?![\d-])/g],
  ['법인등록번호', /(?<![\d-])\d{6}-\d{7}(?![\d-])/g],
  ['계좌번호(붙임표)', /(?<![\d-])\d{3,6}-\d{2,6}-\d{5,8}(?![\d-])/g],
  /* ⚠ 아래 셋은 «검사가 통과하는 동안» 실제로 남아 있던 꼴이다. 왜 못 잡았나:
       · 은행 이름 — /\b…은행\b/ 의 \b 는 «한글 앞에서 성립하지 않는다».
         자바스크립트 \b 는 \w(영문·숫자·밑줄) 경계라, 한글만 있는 자리에는 경계가 없다.
       · 계좌번호 — 붙임표가 ASCII 하이픈이 아니라 en-dash(–) 였다(100 – 034 – 3944 13).
       · 사업자번호 — 띄어 쓴 꼴이고 칸이 한 칸이 아니었다(208 87  00610).
     그래서 셋 다 «칸 수를 느슨하게, 붙임표 종류를 넓게» 본다. */
  ['사업자번호(띄어쓰기)', /(?<![\d-])\d{3}\s+\d{2}\s+\d{5}(?![\d-])/g],
  ['은행 이름', /(하나|국민|신한|우리|농협|기업|카카오|토스|새마을|수협|SC제일|씨티)은행/g],
];
/* 회사 이름 꼴 — 갈래를 «따로» 세워 둔다.
   ⚠ 표기어(주식회사 등)를 대괄호 안에 넣으면 낱자로 지워져 「대주건설」이 「대건설」이 된다.
     그 사고를 막는 검사(company-name-normalize)는 대괄호 «근처»의 표기어를 모두 잡는데,
     정규식을 한 줄에 적으면 배열 대괄호 [ 와 [가-힣] 사이에 표기어가 끼어 잘못 걸린다.
     검사를 느슨하게 하는 대신, 여기를 또렷하게 나눠 적는다. */
const CO_PREFIX = '(?:\\(주\\)|㈜|주식회사|유한회사)';
const CO_TAIL = '(?:소프트|산업|산업사|기업|전자|건설|화학|테크|기술|정밀|물산|상사|중공업|제강|섬유|식품|유통|엔지니어링)';
const CO_NAME_CELL = new RegExp('^\\s*' + CO_PREFIX + '?\\s*[가-힣A-Za-z]{2,}' + CO_TAIL + '\\s*(?:\\(주\\)|㈜)?\\s*$');

/* 띄어 쓴 계좌번호는 «한 칸 안에서만» 본다.
   표 전체를 납작하게 펴서 보면 옆 칸 예산 숫자들이 이어 붙어(200 200 100) 늘 울어 댄다.
   우는 검사는 아무도 안 읽는다. */
const CELL_PATTERNS = [
  ['계좌번호(띄어쓰기·특수 붙임표)', /^\s*\d{2,6}(?:[\s‐-―-]+\d{2,7}){2,}\s*$/],
  /* ⚠ 2026-09-07: 임대차계약서 임대인 칸에 «남의 회사 이름»이 그대로 있었다.
       이 검사가 통과하는 동안 공개 파일에 남아 있었다. 왜 못 잡았나 —
       ① 사람 이름 자리(NAME_SLOTS)만 봤고 «회사 이름» 규칙이 없었다.
       ② 표를 납작하게 편 글로 보면 칸이 이어 붙어(「…소프트주소」) 이름 끝이 사라진다.
       그래서 «칸 하나»를 통째로 보고, 회사 꼬리로 끝나는 칸을 잡는다. */
  ['회사 이름이 든 칸', CO_NAME_CELL],
];

/* ⚠ 이름·주소·계좌만 보던 동안, 남이 실제로 낸 «사업 수치»가 69가지 남아 있었다.
     하나하나는 개인정보가 아니지만, 인가일 2020.04.22 + 근로자 65명 + 업종 +
     출연금 1,000만원이 한 서식에 모이면 어느 기금인지 좁혀진다.
     걷어내기(stripBaked)는 «화면»에서만 도는데, 이 저장소는 파일째 공개된다 —
     소스를 열면 그대로 읽혔다. 서식 24종 151곳을 빈칸으로 바꾸고, 여기서 다시 막는다.

   서식의 «틀»은 남겨야 하므로 둘레 글을 보고 거른다 — 법령 날짜(개정·시행·신설·제정)와
   요율 구간(미만·이상), 안내문(「위원이 4명 이상일 경우」)은 서식의 일부다.
   느슨하게 잡으면 늘 울어 대고, 그러면 아무도 안 읽는다. */
const BIZ_PATTERNS = [
  ['남의 날짜', /(?:19|20)\d{2}\s*[.년]\s*\d{1,2}\s*[.월]\s*\d{1,2}|(?<![\d.])\d{2}\.\d{2}\.\d{2}(?![\d.])/g],
  ['남의 해', /(?:19|20)\d{2}\s*년도?/g],
  ['남의 한글 금액', /[일이삼사오육칠팔구십][가-힣]{0,4}[백천만억]원(?:정)?/g],
  ['남의 사람 수', /[1-9][0-9]*\s*명/g],
  ['남의 금액', /\d{1,3}(?:,\d{3})+/g],
];
const FORM_TEXT = /개정|시행|신설|제정|법률|대통령령|고용노동부령|미만|이상|이내|이하/;
/* 규정이 정한 요율표는 남의 값이 아니라 «서식의 일부»다.
   제도도입 비용 청구내역서의 수당 200·300·400·470만원과 추가(심화컨설팅) 1,000이 그렇다.
   구간(미만·이상)이 «윗줄»에 있어 둘레 글로는 못 가른다 — 여기 적어 둔다.
   ⚠ 서식 이름과 값을 «함께» 못 박는다. 넓게 열어 두면 다른 값이 슬며시 들어온다. */
const RATE_OK = {};   /* 인센티브 비용청구서를 뗀 뒤로는 봐줄 서식이 없다 */

/* 사람 이름은 낱말만 보고는 못 가른다 — 서식에는 「서명·성명·확인」처럼
   이름처럼 생긴 말이 잔뜩이다. 그래서 둘을 «함께» 본다:
     ① 이름이 들어갈 자리인가 (위원명·컨설턴트명·대표이사 칸)
     ② 그 글자가 «흔한 성»으로 시작하고, 서식 낱말이 아닌가
   느슨하게 잡으면 늘 울어 대고, 그러면 아무도 안 읽는다. */
const SURNAME = /^(김|이|박|최|정|강|조|윤|장|임|한|오|서|신|권|황|안|송|류|전|홍|고|문|양|손|배|백|허|남|심|노|하|곽|성|차|주|우|구|나|민|유|진|지|엄|채|원|천|방|공|현|함|변|염|여|추|도|소|석|선|설|마|길|연|위|표|명|기|반|왕|옥|육|인|맹|제|모|탁|국|어|은|편|용)/;
const FORM_WORD = new Set(['서명', '성명', '날인', '확인', '위원', '이사', '감사', '대표', '신청',
  '계좌', '은행', '금액', '주소', '전화', '구분', '비고', '합계', '출석', '찬성', '기금',
  '명칭', '직책', '연번', '회차', '수량', '종류', '내역', '계좌번호', '컨설턴트명', '위원명']);
const looksName = s => s && s.length >= 2 && s.length <= 4 && SURNAME.test(s) && !FORM_WORD.has(s);
const NAME_SLOTS = [
  ['협의회 위원명', /(?:근로자|사용자)위원\s*<\/td>\s*<td[^>]*>\s*([가-힣]{2,4})\s*</g],
  ['컨설턴트명', /컨설턴트명\s*<\/td>\s*<td[^>]*>\s*([가-힣]{2,4})\s*</g],
  ['출연확인서 대표이사', /대표이사\s*([가-힣]{2,4})\s*\(/g],
  ['신청인', /신청인\s+([가-힣]{2,4})\s*\(/g],
];

let total = 0;
for (const k of Object.keys(F)) {
  const raw = String(F[k]);
  const txt = raw.replace(/<[^>]+>/g, ' ').replace(/&[a-z]+;/g, ' ');
  const found = [];
  for (const [name, re] of PATTERNS) {
    const m = txt.match(re);
    if (m) found.push(name + ': ' + [...new Set(m)].slice(0, 3).map(s => s.trim().slice(0, 52)).join(' / '));
  }
  // 칸 단위로 볼 것들 — 표를 납작하게 펴면 옆 칸이 이어 붙어 거짓 경보가 난다
  for (const [name, re] of CELL_PATTERNS) {
    const cells = [...raw.matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/g)]
      .map(m => m[1].replace(/<[^>]*>/g, '').replace(/&[a-z]+;/g, ' '));
    const hits = cells.filter(c => re.test(c)).map(c => c.replace(/\s+/g, ' ').trim());
    if (hits.length) found.push(name + ': ' + [...new Set(hits)].slice(0, 3).join(' / '));
  }
  /* 남의 사업 수치 — 둘레 글이 서식의 틀이면 넘어간다 */
  const flat = txt.replace(/\s+/g, ' ');
  for (const [name, re] of BIZ_PATTERNS) {
    re.lastIndex = 0;
    const hits = new Set();
    let m;
    while ((m = re.exec(flat))) {
      const around = flat.slice(Math.max(0, m.index - 26), m.index + m[0].length + 18);
      if (FORM_TEXT.test(around)) continue;
      if (RATE_OK[k] && RATE_OK[k].has(m[0].trim())) continue;   // 규정이 정한 요율
      hits.add(m[0].trim());
    }
    if (hits.size) found.push(name + ': ' + [...hits].slice(0, 4).join(' / '));
  }
  for (const [name, re] of NAME_SLOTS) {
    const hits = [...raw.matchAll(re)].map(m => m[1]).filter(looksName);
    if (hits.length) found.push(name + '에 이름이 남음: ' + [...new Set(hits)].join(' / '));
  }
  if (found.length) { total++; console.log('■ ' + k); found.forEach(f => console.log('    ' + f)); }
}
console.log(total ? '\n총 ' + total + '종에서 발견' : '\n✓ 전 서식 깨끗함 (' + Object.keys(F).length + '종)');
process.exit(total ? 1 : 0);
