/* 노동 뉴스·법령 브리핑을 만든다 — 매일 아침 공지사항에 저절로 올라간다.
   ═══════════════════════════════════════════════════════════════════════════
   대표 결정 2026-08-31: 「노동뉴스 + 법령 완전자동」.

   ★ 기사 «본문»은 옮기지 않는다 — 남의 글이다.
     제목과 날짜, 그리고 «원문으로 가는 링크»까지가 우리가 실을 수 있는 것이다.
     읽으실 분은 그 신문사로 간다. 이건 취향이 아니라 저작권이다.
     (법령은 저작권 대상이 아니라 그대로 실어도 된다.)

   ★ 이 파일은 «글자를 다루는 일»만 한다. 바깥을 두드리는 것은 index.js 가 한다 —
     그래야 검사가 인터넷 없이 돈다.

   ★ 자동이라서 더 조심할 것
     ① 못 읽으면 «아무것도 안 올린다». 빈 브리핑을 올리면 그날 공지가 빈 껍데기가 된다.
     ② 노동과 무관한 기사를 거른다(신문사 RSS 에 다른 매체 글이 섞여 온다 — 실제로 봤다).
     ③ 같은 날 두 번 올리지 않는다(날짜가 열쇠다). */

/* XML 이 감싸 놓은 것을 «푼다» — &amp; 는 원래 & 였다.
   ★ 안 풀면 두 번 감싸진다. 법제처 링크가 실제로 그랬다:
     XML 의 `?OC=test&amp;target=law` 를 그대로 두고 다시 감싸 `&amp;amp;` 가 되었고,
     브라우저는 그것을 `&amp;target=law` 로 읽어 엉뚱한 곳으로 갔다.
     「법제처에서 보기」를 눌러도 그 법령이 안 나오는데, 아무 오류도 안 난다.
   ★ & 를 «맨 나중에» 푼다 — 먼저 풀면 `&amp;lt;` 가 `<` 까지 되어 버린다. */
function 풀기(s) {
  return String(s == null ? "" : s)
    .replace(/&lt;/g, "<").replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&#0*39;/g, "'")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&");
}

/* ── 남이 준 XML 에서 글자 뽑기 ── */
function 뽑기(블록, 태그) {
  const m = new RegExp("<" + 태그 + "[^>]*>(?:<!\\[CDATA\\[)?([\\s\\S]*?)(?:\\]\\]>)?</" + 태그 + ">")
    .exec(String(블록 == null ? "" : 블록));
  return m ? 풀기(m[1].replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim() : "";
}

function 감싸기(s) {
  return String(s == null ? "" : s)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/* ── ① 노동 뉴스 (RSS) ── */

/* 노동과 «상관있는» 글만 남긴다.
   ★ 신문사 RSS 에는 다른 매체 글이 섞여 온다(실제로 「파인데일리 - 정치」가 왔다).
     자동으로 올라가는 자리라, 걸러 내지 않으면 엉뚱한 기사 제목이 법인 이름으로 나간다. */
const 노동말 = [
  "노동", "근로", "임금", "해고", "산재", "산업재해", "안전보건", "중대재해",
  "노조", "노동조합", "단체교섭", "파업", "최저임금", "고용", "실업", "퇴직",
  "연차", "휴가", "근무", "직장", "노무", "노동위원회", "고용노동부", "산업안전"
];
/* ★ 낱말이 맞아도 «내보내면 안 되는» 글. 목업을 보고 찾았다 —
     「[부고] ○○○ 노동대학원장 빙모상」이 우리 공지에 올라와 있었다.
     낱말(노동)은 맞지만 손님에게 알릴 소식이 아니고,
     남의 집 상사(喪事)를 우리 홈페이지가 자동으로 옮기는 것은 예의도 아니다. */
const 뺄말뉴스 = ["부고", "부음", "빙모상", "빙부상", "별세", "조의", "결혼"];

function 노동글인가(제목) {
  const t = String(제목 == null ? "" : 제목);
  if (뺄말뉴스.some(function (w) { return t.indexOf(w) >= 0; })) return false;
  return 노동말.some(function (w) { return t.indexOf(w) >= 0; });
}

function 뉴스읽기(xml, 언론사) {
  const 글 = String(xml == null ? "" : xml).split(/<item[^>]*>/).slice(1);
  return 글.map(function (b) {
    return {
      제목: 뽑기(b, "title"),
      링크: 뽑기(b, "link"),
      날짜: 뽑기(b, "pubDate"),
      언론사: 언론사 || ""
    };
  }).filter(function (x) {
    return x.제목 && /^https?:\/\//.test(x.링크) && 노동글인가(x.제목);
  });
}

/* ── ② 법령 (법제처 공동활용) ── */
function 법령읽기(xml) {
  const 덩이 = String(xml == null ? "" : xml).split(/<law[^>]*>/).slice(1);
  return 덩이.map(function (b) {
    return {
      이름: 뽑기(b, "법령명한글"),
      구분: 뽑기(b, "법령구분명"),
      고친결: 뽑기(b, "제개정구분명"),
      공포일: 뽑기(b, "공포일자"),
      시행일: 뽑기(b, "시행일자"),
      부처: 뽑기(b, "소관부처명"),
      링크: 뽑기(b, "법령상세링크")
    };
  }).filter(function (x) { return x.이름; });
}

/* 20260825 → 2026-08-25 */
function 날짜꼴(s) {
  const t = String(s == null ? "" : s).replace(/\D/g, "");
  return t.length === 8 ? t.slice(0, 4) + "-" + t.slice(4, 6) + "-" + t.slice(6) : t;
}

/* ★ 노무 낱말로 찾아도 «손님에게 쓸모 없는» 법령. 목업을 보고 찾았다 —
     「고용노동부와 그 소속기관 직제」가 법령 소식 맨 위에 올라와 있었다.
     부처가 제 조직·정원을 고친 것이라, 사업장이 챙길 일이 하나도 없다.
     이런 것이 위를 차지하면 정작 봐야 할 「임금채권보장법」이 밀려난다. */
const 뺄말법령 = ["직제", "정원", "위원회 구성", "훈령", "청사"];
function 쓸모있는법령인가(이름) {
  const t = String(이름 == null ? "" : 이름);
  return !뺄말법령.some(function (w) { return t.indexOf(w) >= 0; });
}

/* 겹치는 법령을 하나로 모으고, «공포일이 가까운 것»부터 */
function 법령추리기(목록, 몇개) {
  const 본것 = {};
  return (목록 || [])
    .filter(function (x) { return 쓸모있는법령인가(x.이름); })
    .filter(function (x) { if (본것[x.이름]) return false; 본것[x.이름] = 1; return true; })
    .sort(function (a, b) { return String(b.공포일).localeCompare(String(a.공포일)); })
    .slice(0, 몇개 || 5);
}

/* ── ③ 브리핑 한 장 만들기 ──
   ★ 매일치와 주간치가 «같은 몸통»을 쓴다. 글 모양을 두 벌로 두면 한쪽만 낡는다.
     다른 것은 머리말·꼬리말·제목·몇 건까지 싣나, 이 넷뿐이다. */
function 글짓기(뉴스, 법령, 옷) {
  const 뉴스목록 = (뉴스 || []).slice(0, 옷.뉴스몇 || 7);
  const 법령목록 = (법령 || []).slice(0, 옷.법령몇 || 5);

  /* ★ 둘 다 비면 «만들지 않는다». 빈 브리핑을 올리면 그날 공지가 빈 껍데기가 된다. */
  if (!뉴스목록.length && !법령목록.length) return null;

  const 줄 = [];
  줄.push('<p>' + 옷.머리말 + '</p>');

  if (법령목록.length) {
    줄.push('<h3>법령 소식</h3>');
    줄.push('<ul>');
    법령목록.forEach(function (x) {
      줄.push('<li><strong>' + 감싸기(x.이름) + '</strong>'
        + (x.구분 ? ' (' + 감싸기(x.구분) + ')' : '')
        + (x.고친결 ? ' — ' + 감싸기(x.고친결) : '')
        + '<br><span>공포 ' + 감싸기(날짜꼴(x.공포일))
        + ' · 시행 ' + 감싸기(날짜꼴(x.시행일))
        + (x.부처 ? ' · ' + 감싸기(x.부처) : '') + '</span>'
        + (x.링크 ? ' <a href="https://www.law.go.kr' + 감싸기(x.링크)
            + '" target="_blank" rel="noopener">법제처에서 보기</a>' : '')
        + '</li>');
    });
    줄.push('</ul>');
  }

  if (뉴스목록.length) {
    줄.push('<h3>노동 뉴스</h3>');
    /* ★ 제목과 링크만 싣는다 — 기사 본문은 남의 글이다 */
    줄.push('<ul>');
    뉴스목록.forEach(function (x) {
      줄.push('<li><a href="' + 감싸기(x.링크) + '" target="_blank" rel="noopener">'
        + 감싸기(x.제목) + '</a>'
        + (x.언론사 ? ' <span>· ' + 감싸기(x.언론사) + '</span>' : '') + '</li>');
    });
    줄.push('</ul>');
    줄.push('<p><span>기사 제목과 링크만 싣습니다. 본문은 각 언론사 홈페이지에서 보실 수 있습니다.</span></p>');
  }

  줄.push('<p><span>' + 옷.꼬리말 + '</span></p>');

  return {
    제목: 옷.제목,
    본문: 줄.join("\n"),
    요약: 옷.요약(법령목록.length, 뉴스목록.length),
    날짜: 옷.날짜,
    기간: 옷.기간 || 옷.날짜
  };
}

/* 하루치 — 남겨 둔다. 「오늘 하루」만 뽑아 보고 싶을 때가 있다. */
function 브리핑(뉴스, 법령, 오늘) {
  const 날 = String(오늘 || "").slice(0, 10);
  return 글짓기(뉴스, 법령, {
    뉴스몇: 7, 법령몇: 5, 날짜: 날,
    머리말: 감싸기(날) + ' 기준, 인사·노무 관련 소식을 모았습니다.',
    꼬리말: '이 글은 푸른ERP 가 매일 아침 자동으로 올립니다.',
    제목: '노동 뉴스·법령 브리핑 (' + 날 + ')',
    요약: function (법, 뉴) { return '인사·노무 관련 법령 ' + 법 + '건, 노동 뉴스 ' + 뉴 + '건'; }
  });
}

/* ══════════════════════════════════════════════════════════════════════════
   ④ 주간 뉴스레터 (대표 지시 2026-09-02 「공지사항은 뉴스레터와 같이 주 1회」)
   ══════════════════════════════════════════════════════════════════════════
   ★ 왜 «날마다 모아 두었다가» 주 1회 내는가 —
     신문사 RSS 는 최근 50개만 준다. 그것이 실제로 «이틀치»뿐이었다
     (2026-09-02 실측: 50개 = 8/30~9/1, 노동 관련 31건).
     그래서 주 1회만 읽으면 「주간」이라 이름 붙이고 이틀치만 싣게 된다.
     날마다 제목·링크만 모아 두었다가 월요일에 한 장으로 낸다.

   ★ 모으는 것은 «제목·링크·언론사·모은날»뿐이다 — 본문은 남의 글이라 담지 않는다.
     노무법인 이름으로 나가는 자리라 더 그렇다.

   ★ 같은 기사가 여러 날 RSS 에 남아 있다 — 링크를 열쇠로 삼아 겹치지 않게 한다. */

/* 파이어베이스 열쇠로 못 쓰는 글자가 있다: . # $ / [ ] */
function 링크열쇠(링크) {
  return String(링크 == null ? '' : 링크).replace(/[.#$/[\]]/g, '_').slice(0, 200);
}

/* 며칠 전 날짜를 「2026-08-26」꼴로 */
function 며칠전(오늘, 며칠) {
  const d = new Date(String(오늘).slice(0, 10) + 'T00:00:00Z');
  if (isNaN(d)) return '';
  d.setUTCDate(d.getUTCDate() - (며칠 || 0));
  return d.toISOString().slice(0, 10);
}

/* 모아 둔 것에 오늘 읽은 것을 얹는다. 이미 있는 링크는 넣지 않는다.
   돌려주는 것: { 모음, 새로: 몇 건 늘었나 } */
function 모으기(모아둔것, 오늘뉴스, 오늘) {
  const 날 = String(오늘 || '').slice(0, 10);
  const 모음 = Object.assign({}, 모아둔것 || {});
  let 새로 = 0;
  (오늘뉴스 || []).forEach(function (x) {
    if (!x || !x.링크 || !x.제목) return;
    const 열쇠 = 링크열쇠(x.링크);
    if (모음[열쇠]) return;
    모음[열쇠] = { 제목: x.제목, 링크: x.링크, 언론사: x.언론사 || '', 모은날: 날 };
    새로++;
  });
  return { 모음: 모음, 새로: 새로 };
}

/* 지난 며칠치만 남기고 턴다 — 안 털면 모음이 끝없이 부푼다 */
function 오래된것털기(모아둔것, 오늘, 며칠) {
  const 자른날 = 며칠전(오늘, 며칠 || 14);
  const 남길것 = {};
  Object.keys(모아둔것 || {}).forEach(function (k) {
    const v = 모아둔것[k];
    if (v && String(v.모은날 || '') >= 자른날) 남길것[k] = v;
  });
  return 남길것;
}

/* 모음에서 «지난 한 주» 것만 골라 최신순으로 */
function 주간뉴스고르기(모아둔것, 오늘, 며칠) {
  const 자른날 = 며칠전(오늘, (며칠 || 7) - 1);
  return Object.keys(모아둔것 || {})
    .map(function (k) { return 모아둔것[k]; })
    .filter(function (v) {
      /* ★ 창고를 다시 읽을 때도 거르개를 «한 번 더» 건다.
         모을 때 이미 걸렀지만, 거르개를 늘리기 «전에» 담아 둔 것이 창고에 남아 있다
         (2026-09-02 에 부고를 뺐으니, 그 전에 담긴 부고는 창고 안에 있다).
         여기서 막지 않으면 주간 브리핑으로 나간다. */
      return v && v.제목 && v.링크 && 노동글인가(v.제목)
        && String(v.모은날 || '') >= 자른날;
    })
    .sort(function (a, b) { return String(b.모은날).localeCompare(String(a.모은날)); });
}

/* 주간 뉴스레터 한 장.
   ★ 매일치와 달리 «기간»을 앞세운다 — 뉴스레터는 「지난 한 주」가 이름이다. */
function 주간브리핑(뉴스, 법령, 오늘, 며칠) {
  const 날 = String(오늘 || '').slice(0, 10);
  const 기간 = 며칠전(날, (며칠 || 7) - 1) + ' ~ ' + 날;
  return 글짓기(뉴스, 법령, {
    뉴스몇: 12, 법령몇: 8, 날짜: 날, 기간: 기간,
    머리말: 감싸기(기간) + ' 한 주 동안의 인사·노무 소식을 모았습니다.',
    꼬리말: '이 글은 푸른ERP 가 매주 월요일 아침 자동으로 올립니다.',
    제목: '주간 노동 브리핑 (' + 기간 + ')',
    요약: function (법, 뉴) {
      return '지난 한 주 인사·노무 법령 ' + 법 + '건, 노동 뉴스 ' + 뉴 + '건';
    }
  });
}

