/* 뉴스레터 열람·클릭 추적 — 판단하는 층 (바깥을 두드리지 않는다)
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-03: 「발송이 된것 과 수신이된것 열람 미열람을 정확하게 확인하고
   3회이상 미열람일 경우 … 미열람 사업장 제외하는 시스템이 필요하다」

   ★ 이 파일은 파이어베이스도 인터넷도 모른다 — 주소를 «읽고 만드는» 규칙만 있다.
     그래야 검사가 인터넷 없이 돌고, 서버와 편지짓기가 «같은 규칙»을 쓴다.

   ⚠ 클릭 추적의 급소 — 목적지 주소(u=https://…)를 그대로 실으면 «누구나 우리 주소로
     남을 속이는 링크»를 만들 수 있다(열린 리다이렉트 · 피싱). 우리 도메인이라
     받는 쪽이 더 잘 믿는다는 점이 더 나쁘다.
     그래서 주소 대신 «번호»만 싣는다 — 보낼 때 회차에 링크 목록을 적어 두고,
     번호로 그 목록을 찾아 보낸다. 목록에 없는 번호는 어디로도 안 보낸다. */
'use strict';

/* 파이어베이스 열쇠에 못 쓰는 글자 — 자리 이름으로 쓰려면 바꿔야 한다 */
function 주소열쇠(email) {
  return String(email == null ? '' : email).trim().toLowerCase().replace(/[.#$/[\]]/g, '_');
}

/* 회차 열쇠도 자리 이름이 된다 — 같은 잣대로 씻는다 */
function 회차열쇠(v) {
  return String(v == null ? '' : v).trim().replace(/[.#$/[\]]/g, '_').slice(0, 40);
}

/* 물음표 뒤에 붙는 것들을 읽는다. ⚠ 없는 값·이상한 값에 터지지 않아야 한다 —
   받는 쪽 메일 프로그램이 주소를 조금씩 바꿔 부르는 일이 있다. */
function 읽기(q) {
  const o = q && typeof q === 'object' ? q : {};
  const 회차 = 회차열쇠(o.i);
  const 주소 = 주소열쇠(o.e);
  let 번호 = Number(o.n);
  if (!isFinite(번호) || 번호 < 0 || 번호 > 999) 번호 = -1;
  return { 회차: 회차, 주소: 주소, 번호: Math.floor(번호), ok: !!(회차 && 주소) };
}

/* 이 회차의 링크 목록에서 번호로 찾는다.
   ⚠ 목록에 없으면 «빈 값»을 돌려준다 — 어디로도 보내지 않는다. 그것이 안전한 쪽이다.
   ⚠ http/https 만 — javascript: 같은 것이 목록에 잘못 들어가도 여기서 막는다. */
function 링크찾기(링크들, 번호) {
  const L = Array.isArray(링크들) ? 링크들 : [];
  if (번호 < 0 || 번호 >= L.length) return '';
  const u = String(L[번호] == null ? '' : L[번호]).trim();
  return /^https?:\/\//i.test(u) ? u : '';
}

/* 열람·클릭을 적을 자리 — newsletter/opens/{회차}/{주소} */
function 적을자리(회차, 주소) {
  return 'newsletter/opens/' + 회차열쇠(회차) + '/' + 주소열쇠(주소);
}

/* 보낼 때 적어 두는 자리 — 「이 회차를 이 주소에 보냈다」.
   ⚠ 이것이 없으면 «보낸 적 없는 회차»를 미열람으로 세게 된다. */
function 보냄표(회차, 주소) {
  return 적을자리(회차, 주소) + '/보냄';
}

/* ══════════════════════════════════════════════════════════════════════════
   받는 분을 «뜻 없는 번호»로 부른다 (대표 지시 2026-09-03 「고쳐라」)
   ══════════════════════════════════════════════════════════════════════════
   ⚠ 왜 고치나 — 추적 주소에 메일 주소가 그대로 실려 있었다:
       /newsOpen?i=2026-09-1&e=hong_example_kr
     받는 쪽 메일 프로그램·중계 서버·우리 서버 기록에 «누구인지»가 남는다.
     기능에 필요한 것은 «누구인지 우리가 알아보는 것»이지, 주소를 실어 나르는 것이 아니다.
   ★ 그래서 회차마다 「번호 → 주소」 대장을 두고, 편지에는 번호만 싣는다.
     번호는 뜻이 없어, 새어도 그 자체로는 누구인지 알 수 없다.
   ★ 덤으로 «아무나 표를 켜는 일»도 막힌다 — 우리가 낸 번호가 아니면 아무 일도 안 한다.
     예전에는 주소만 알면 남의 열람 표를 켤 수 있었다. */

/* 대장 자리 — newsletter/issues/{회차}/받는이/{번호} = 주소열쇠 */
function 받는이자리(회차, 번호) {
  return 'newsletter/issues/' + 회차열쇠(회차) + '/받는이/' + 번호열쇠(번호);
}

/* 번호도 파이어베이스 자리 이름이 된다 — 같은 잣대로 씻고, 길이를 묶는다.
   ⚠ 씻고 나서 비면 «빈 자리»가 되어 대장 전체를 가리킨다. 그때는 빈 값을 준다. */
function 번호열쇠(v) {
  return String(v == null ? '' : v).trim().replace(/[^A-Za-z0-9_-]/g, '').slice(0, 40);
}

/* 새 번호 하나 — 회차 안에서만 겹치지 않으면 된다.
   ⚠ 짐작할 수 있으면 안 된다(짐작하면 남의 표를 켠다). 그래서 «넉넉히 길게» 만든다.
     Math.random 만 쓰지 않는다 — 같은 밀리초에 여러 통을 만들면 겹칠 수 있다. */
function 새번호(rnd) {
  const r = typeof rnd === 'function' ? rnd : Math.random;
  let s = '';
  while (s.length < 22) s += Math.floor(r() * 36 ** 8).toString(36);
  return s.slice(0, 22);
}

/* 편지에 넣을 주소들 — 편지짓기와 서버가 «같은 모양»을 써야 한다.
   ⚠ {추적열쇠} 는 보낼 때 통마다 그 사람 주소로 바뀐다(mail-bulk fill).
     여기서 실제 주소를 넣지 않는 까닭은, 편지 몸통이 한 번만 만들어지기 때문이다. */
function 열람그림주소(밑주소, 회차) {
  return String(밑주소 || '').replace(/\/+$/, '')
    + '/newsOpen?i=' + encodeURIComponent(회차열쇠(회차)) + '&e={추적열쇠}';
}
function 클릭주소(밑주소, 회차, 번호) {
  return String(밑주소 || '').replace(/\/+$/, '')
    + '/newsClick?i=' + encodeURIComponent(회차열쇠(회차))
    + '&e={추적열쇠}&n=' + Math.max(0, Math.floor(Number(번호) || 0));
}

/* 1×1 투명 그림 — 열람을 적은 뒤 이것을 돌려준다.
   ⚠ 캐시를 막아야 한다. 캐시가 되면 두 번째 열람이 우리 서버에 안 온다. */
const 빈그림 = Buffer.from(
  'R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7', 'base64');

module.exports = {
  주소열쇠, 회차열쇠, 읽기, 링크찾기, 적을자리, 보냄표,
  받는이자리, 번호열쇠, 새번호,
  열람그림주소, 클릭주소, 빈그림,
};
