/* 반출 기록 정리 — 2년이 지난 줄만 고른다 (대표 결정 2026-09-02: 「2년 · 서버가 달마다」)
   ═══════════════════════════════════════════════════════════════════════════
   ■ 왜 서버가 하나
   반출 기록은 규칙이 `!data.exists()` 다 — **새로 만드는 것만** 된다.
   고치기·지우기는 대표도 못 한다. 일부러 그렇게 두었다: 자기 기록을 지울 수 있으면
   기록이 아무 뜻이 없다. 그래서 정리는 앱 «밖»에서만 할 수 있고,
   관리자 권한으로 도는 서버가 그 자리다. 앱의 「아무도 못 지운다」는 그대로 남는다.

   ■ ⚠⚠ 이것은 «감사 기록을 지우는» 일이다
   그래서 조심하는 자리를 코드에 못박는다:
     ① 날짜를 못 읽는 줄은 **안 지운다**. 언제 것인지 모르는 것을 지우면 안 된다.
     ② 앞날 날짜(미래)도 **안 지운다** — 시계가 틀렸거나 손댄 자리다.
     ③ 자르는 날이 이상하면(앞날·0) **아무것도 안 지운다.**
     ④ 한 번에 지우는 수에 **상한**을 둔다. 남은 것은 다음 달에.
     ⑤ 지운 셈을 «남긴다» — 조용히 지우면 그것이 또 하나의 감사 구멍이다.

   ■ 이 부품은 서버에서만 쓴다(functions/ 안) — 화면에서는 지울 길이 아예 없다. */
"use strict";

/* 보유기간 — 대표 결정 2026-09-02. 검사고정-허용: 이 숫자가 «규칙»이다(용량이 아니라 보유기간). */
const 보유_일 = 730;                 /* 2년 */
const 한번에_상한 = 500;             /* 한 번에 이만큼까지 — 남은 것은 다음 달에 */
const 하루 = 24 * 60 * 60 * 1000;

/* 자르는 날 — 이보다 «앞선» 기록만 지운다.
   ⚠ 지금 시각이 이상하면 0 을 돌려준다. 부르는 쪽은 0 이면 아무것도 안 지운다. */
function 자르는날(지금, 일 = 보유_일) {
  const t = Number(지금);
  if (!isFinite(t) || t <= 0) return 0;
  const d = Number(일);
  if (!isFinite(d) || d <= 0) return 0;
  return t - d * 하루;
}

/* 줄 하나가 «지울 것»인가.
   돌려주는 것: 'old'(지운다) · 'keep'(남긴다) · 'unknown'(날짜를 못 읽었다) */
function 줄판정(rec, 자름, 지금) {
  if (!rec || typeof rec !== "object") return "unknown";
  const at = rec.at;
  /* ⚠ 숫자가 아니면 못 본 것으로 둔다 — 글자로 적힌 날짜, 빈 칸, null 모두 여기다.
     언제 것인지 모르는 감사 기록을 지우면 되돌릴 길이 없다. */
  if (typeof at !== "number" || !isFinite(at) || at <= 0) return "unknown";
  /* ⚠ 앞날 날짜도 안 지운다 — 시계가 틀렸거나 누가 손댄 자리다.
     여기서 지우면 «가장 최근» 기록이 사라진다. */
  if (지금 && at > Number(지금)) return "unknown";
  return at < 자름 ? "old" : "keep";
}

/* 지울 줄을 고른다 — 서버에 쓰기 전에 여기서 다 가린다.
   rows: { 열쇠: 기록 } · 돌려주는 것:
     { 지울것:[열쇠], 남길것:n, 못본것:n, 넘친것:n, 자름, 멈춤 } */
function 고르기(rows, 지금, 옵션) {
  const o = 옵션 || {};
  const 상한 = Number(o.상한) || 한번에_상한;
  const 자름 = 자르는날(지금, o.일);
  const out = { 지울것: [], 남길것: 0, 못본것: 0, 넘친것: 0, 자름: 자름, 멈춤: "" };

  /* ③ 자르는 날이 이상하면 아무것도 안 한다 */
  if (!자름 || 자름 <= 0) { out.멈춤 = "자르는 날을 셈하지 못했습니다"; return out; }
  if (자름 > Number(지금)) { out.멈춤 = "자르는 날이 앞날입니다"; return out; }

  const 열쇠들 = (rows && typeof rows === "object") ? Object.keys(rows) : [];
  /* 오래된 것부터 지운다 — 상한에 걸려 남더라도 «가장 오래된 것»이 먼저 없어진다 */
  const 후보 = [];
  열쇠들.forEach(function (k) {
    const v = 줄판정(rows[k], 자름, 지금);
    if (v === "old") 후보.push({ k: k, at: rows[k].at });
    else if (v === "unknown") out.못본것++;
    else out.남길것++;
  });
  후보.sort(function (a, b) { return a.at - b.at; });
  후보.slice(0, 상한).forEach(function (x) { out.지울것.push(x.k); });
  out.넘친것 = Math.max(0, 후보.length - 상한);
  return out;
}

/* 지울 자리표 — 파이어베이스에 한 번에 넘길 꼴.
   ⚠ 지우는 자리를 여기서만 만든다. 두 곳에서 만들면 한쪽이 엉뚱한 자리를 지운다. */
function 지울자리(열쇠들, 뿌리) {
  const r = String(뿌리 || "exportLog");
  const u = {};
  (열쇠들 || []).forEach(function (k) {
    const key = String(k == null ? "" : k);
    if (!key) return;
    u[r + "/" + key] = null;
  });
  return u;
}

/* 남길 셈 한 줄 — 조용히 지우면 그것이 또 하나의 감사 구멍이다.
   ⚠ 이 줄은 exportLog «밖»에 남긴다. 안에 남기면 그 줄도 2년 뒤 지워진다. */
function 셈기록(결과, 지금) {
  return {
    at: Number(지금) || 0,
    자름: 결과.자름 || 0,
    보유일: 보유_일,
    지움: (결과.지울것 || []).length,
    남김: 결과.남길것 || 0,
    못본것: 결과.못본것 || 0,
    남은것: 결과.넘친것 || 0,
    멈춤: 결과.멈춤 || ""
  };
}

module.exports = { 보유_일, 한번에_상한, 자르는날, 줄판정, 고르기, 지울자리, 셈기록 };
