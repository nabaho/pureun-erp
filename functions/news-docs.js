/* ── ③ 실을 만한 자료인가 ──────────────────────────────────────────────
   고용노동부 정책자료실이라 대부분이 노무 자료다. 그래서 «거르기»보다
   «값어치 매기기»가 맞다 — 좋은 것을 위로 올리고, 나쁜 것만 뺀다.

   ★ 「가이드·매뉴얼·안내·지침」이 붙은 것이 사업장에 바로 쓸모가 있다.
     원본 뉴스레터에 실린 두 건이 모두 「활용가이드」였다. */
var 좋은말 = ["가이드", "매뉴얼", "안내서", "해설", "길잡이", "편람", "사례집",
  "표준계약서", "취업규칙", "Q&A", "질의회시", "지침", "안내", "제도"];
var 뺄말 = ["입찰", "공고", "채용", "청렴", "인사발령", "시무식", "축사", "부고",
  "위원 위촉", "정기간행물 등록", "오픈채팅방"];
/* ⚠ 보도자료에는 이런 것이 섞인다 — 사업장이 챙길 일이 아니다 */
var 뺄말보도 = ["공모전", "시상", "표창", "위촉", "간담회 개최", "업무협약", "MOU",
  "기념식", "캠페인 발대", "장관 현장방문",
  /* ⚠ 부처 «제 집 인사»다 — 사업장이 챙길 일이 하나도 없다.
       2026-09-07 실측에서 「노동·산업안전 우수직원 특별승진」이 맨 위에 올라왔다. */
  "특별승진", "우수직원", "승진 임용", "인사 발령", "취임", "이임"];

function 뺄자료인가(제목, 샘키) {
  var t = String(제목 == null ? "" : 제목);
  var 목록 = (샘키 === "moel-news") ? 뺄말.concat(뺄말보도) : 뺄말;
  return 목록.some(function (w) { return t.indexOf(w) >= 0; });
}

function 자료값어치(제목, 샘키) {
  var t = String(제목 == null ? "" : 제목);
  if (뺄자료인가(t, 샘키)) return -1;
  var 점 = 0;
  좋은말.forEach(function (w, i) {
    if (t.indexOf(w) >= 0) 점 += (i < 7 ? 3 : 1);      /* 앞쪽 말이 더 값어치 있다 */
  });
  /* ⚠ 보도자료는 한 칸 낮춰 본다 — 홍보성 글이 섞이고 주간노동뉴스와 겹친다.
       그래도 «자료다운 말»(가이드·지침)이 붙은 보도자료는 여전히 위로 올라온다. */
  if (샘키 === "moel-news") 점 -= 1;
  return 점;
}

/* 「노동동향(2026년 7월)」 → 「노동동향」. 달·해·회차 번호를 떼면 «연속물 이름»이 남는다.
   ★ 왜 필요한가 — 달마다 나오는 것은 이름이 같고 날짜만 다르다. 그대로 둘을 실으면
     인사·노무관리 칸에 「노동동향(7월)」과 「노동동향(6월)」이 나란히 앉는다
     (2026-09-07 실측). 손님에게는 같은 것이 두 번 온 것으로 보인다.
   ⚠ 이름이 통째로 날짜뿐이면 «원래대로» 둔다 — 다듬기가 이름을 지우면 안 된다. */
function 묶음이름(제목) {
  var t = String(제목 == null ? "" : 제목).replace(/\s+/g, " ").trim();
  var 벗긴것 = t
    .replace(/\(\s*['’]?\d{2,4}\s*년?\s*[^()]*\)\s*$/, "")   /* (2026년 7월) · ('24년) */
    .replace(/\(\s*제?\s*\d+\s*[호회차기]?\s*\)\s*$/, "")     /* (제37호) · (12차) */
    .replace(/\s*[-–]\s*\d{4}[.\-/]\d{1,2}.*$/, "")           /* — 2026.07 … */
    .trim();
  return 벗긴것.length >= 4 ? 벗긴것 : t;
}

/* 값어치 높은 것 → 최근 것 차례로. 겹치는 일련번호는 하나만.
   ⚠ 열쇠에 «샘»을 함께 넣는다 — 샘이 다르면 일련번호가 겹칠 수 있다. */
function 자료추리기(목록, 몇개) {
  var 본것 = {};
  var 본묶음 = {};
  return (목록 || [])
    .filter(function (x) { return x && x.제목 && !뺄자료인가(x.제목, x.샘); })
    .filter(function (x) {
      var k = String(x.샘 || "") + "|" + x.일련번호;
      if (본것[k]) return false; 본것[k] = 1; return true;
    })
    .sort(function (a, b) {
      var d = 자료값어치(b.제목, b.샘) - 자료값어치(a.제목, a.샘);
      if (d) return d;
      return String(b.등록일 || "").localeCompare(String(a.등록일 || ""));
    })
    /* ⚠ 겹치기 막기는 «차례를 세운 뒤»에 한다 — 그래야 같은 연속물 가운데
         «가장 최근 것»이 남는다. 세우기 전에 걸면 목록에 먼저 나온 것이 남는다. */
    .filter(function (x) {
      var k = String(x.샘 || "") + "|" + 묶음이름(x.제목).replace(/\s/g, "");
      if (본묶음[k]) return false; 본묶음[k] = 1; return true;
    })
    .slice(0, 몇개 || 6);
}

/* ── ④ 뉴스레터가 쓰는 «한 칸»으로 ─────────────────────────────────────
   ⚠ 여기서 나온 모양이 곧 편지에 그려진다(js/pu-news-tpl.js 의 자료칸).
     칸 이름을 바꾸면 «두 곳»을 함께 고친다. */
function 자료로만들기(상세, 옵션) {
  var d = 상세 || {};
  if (!d.제목) return null;
  var O = 옵션 || {};
  var S = 샘찾기(d.샘 || (O.샘 && O.샘.키));
  var 첫파일 = (d.파일들 || [])[0] || null;
  /* ★ «목록에 적힌 제목»을 앞세운다 (2026-09-07).
     KLI 는 상세 쪽 큰 글씨가 «칸 이름»이라 어느 달 것이든 「국내노동동향」으로 같다.
     목록에는 「노동동향(2026년 7월)」로 달까지 적혀 있다 — 그것이 사람이 고를 이름이다.
     ⚠ 셋을 나란히 실으면 「국내노동동향」이 세 줄 되어 무엇이 무엇인지 알 수 없었다. */
  var 제목 = String(O.목록제목 || "").replace(/\s+/g, " ").trim() || d.제목;
  return {
    갈래: "자료",
    샘: S.키,
    꼭지: S.꼭지,                                /* 어느 꼭지에 넣을지 — 샘이 정한다 */
    제목: 제목,
    발행처: O.발행처 || S.발행처,
    부서: d.부서 || "",
    발행일: d.등록일 || "",
    설명: (d.설명 || "").slice(0, 300),
    목차: S.목차없음 ? [] : 목차뽑기(d.설명, 4),
    표지: "",                                    /* 그림은 나중에 — 없으면 글자 표지 */
    파일: 첫파일 ? 첫파일.주소 : "",
    파일이름: 첫파일 ? 첫파일.이름 : "",
    확장자: 첫파일 ? 첫파일.확장자 : "",
    파일크기: 0,                                 /* 내려받아 본 뒤에 채운다 */
    링크: 상세주소(d.일련번호, S),
    일련번호: String(d.일련번호 || "")
  };
}

/* 모아 둔 것에 오늘 읽은 것을 얹는다 — news-brief 의 모으기 와 같은 손버릇.
   ★ 열쇠는 «샘 + 일련번호»다. 같은 자료가 여러 날 목록 맨 위에 남아 있고,
     샘이 다르면 일련번호가 겹칠 수 있다. */
function 모으기(모아둔것, 오늘자료, 오늘) {
  var 날 = String(오늘 || "").slice(0, 10);
  var 모음 = Object.assign({}, 모아둔것 || {});
  var 새로 = 0;
  (오늘자료 || []).forEach(function (x) {
    if (!x || !x.일련번호 || !x.제목) return;
    var 열쇠 = (String(x.샘 || "moel-policy") + "_" + String(x.일련번호))
      .replace(/[.#$/[\]]/g, "_");
    /* ★ 이미 있는 줄인데 «사본이 없다»면 채워 넣는다 (2026-09-07)
         여태 「있으면 건너뛴다」였다. 그래서 사본 없이 한 번 담긴 자료는 다시 모아도
         영원히 사본을 못 얻고, 편지에 첨부로 못 붙었다 — 실제로 다섯 건이 그랬다.
       ⚠ 모은날은 «옛것»을 지킨다. 새 날로 덮으면 털기(60일)를 날마다 미루게 된다.
       ⚠ 새로 센 것에 넣지 않는다. 새 자료가 온 것이 아니라 빠진 칸을 채운 것이다. */
    if (모음[열쇠]) {
      var 옛 = 모음[열쇠] || {};
      if (!옛.사본 && x.사본) {
        모음[열쇠] = Object.assign({}, 옛, x, { 모은날: 옛.모은날 || 날 });
      }
      return;
    }
    모음[열쇠] = Object.assign({}, x, { 모은날: 날 });
    새로++;
  });
  return { 모음: 모음, 새로: 새로 };
}

/* 오래된 것 털기 — 자료는 뉴스보다 오래 쓸모가 있어 «60일»까지 둔다 */
function 오래된것털기(모아둔것, 오늘, 며칠) {
  var d = new Date(String(오늘 || "").slice(0, 10) + "T00:00:00Z");
  if (isNaN(d)) return Object.assign({}, 모아둔것 || {});
  d.setUTCDate(d.getUTCDate() - (며칠 || 60));
  var 자른날 = d.toISOString().slice(0, 10);
  var 남길것 = {};
  Object.keys(모아둔것 || {}).forEach(function (k) {
    var v = (모아둔것 || {})[k];
    if (v && String(v.모은날 || "") >= 자른날) 남길것[k] = v;
  });
  return 남길것;
}

