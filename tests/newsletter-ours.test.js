/* 기사는 «우리가 쓴 글»만 나간다 · 판례는 «결과만» (대표 지시 2026-09-08)
   ═══════════════════════════════════════════════════════════════════════════
   「뉴스레터 너무 많이 아래로 내려온다 간단하게 결과만 나오게 하고
    매일 노동뉴스를 그대로 나오게 하면 문제가 된다 이 부분도 정리 편집하고
    노동뉴스 참고했다고 정리할 수 있나?」
   대표 결정: «안 쓴 줄은 안 실린다»

   ■ 왜
     ① 판례가 편지 글자의 «83%» 를 먹고 있었다 (2026-09-08 실측, 석 장 1,959자):
        요지 770 · 판시사항 464 · 참조조문 223 · 그 밖 265
        ⚠⚠ 판결문은 저작물이 «아니다»(저작권법 제7조 — 판결·결정·명령).
          빼는 까닭은 «오직 길이»다. 저작권으로 잘못 적어 두면 다음 사람이
          엉뚱한 데까지 지운다.
     ② 유료 구독 매체(매일노동뉴스)의 제목을 매주 여덟 줄 그대로 옮기면
        「그대로 전달」에 가깝다.
        ★ 사실(누가·언제·무엇)은 저작물이 아니라 우리 문장으로 전할 수 있고,
          그 위에 「사업장은 무엇을 챙기나」를 붙이면 그건 우리 저작물이다.

   ■ 이 검사가 지키는 것
     ㉠ 우리 말이 없는 기사는 «편지에 안 나간다» — 사람이 잊어도 기계가 막는다
     ㉡ 우리 말이 있으면 «그것이» 본문이고 제목은 안 나간다
     ㉢ 출처를 «밝힌다» — 참고한 것을 안 밝히면 그것이 더 나쁘다
     ㉣ 이미 «보낸» 회차는 그때 나간 그대로 — 지난 회차가 통째로 사라지면 안 된다
     ㉤ 판례에서 요지·참조조문이 «되살아나지 않는다» */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { 주석걷기, 함수몸 } = require('./helpers/strip-comments.js');

const 뿌리 = path.join(__dirname, '..');
const C = require('../js/pu-news-core.js');
const T = require('../js/pu-news-tpl.js');
const 화면 = 주석걷기(fs.readFileSync(path.join(뿌리, 'pu-news.html'), 'utf8'));

const 설 = { 회사이름: '푸른노무법인', 보내는주소: '370-6@hanmail.net' };
const 기사 = (덧) => Object.assign({ 갈래: '기사', 제목: '원문제목입니다',
  링크: 'https://www.labortoday.co.kr/x', 언론사: '매일노동뉴스' }, 덧 || {});
function 편지(안, 상태) {
  return T.편지짓기({ 회차: C.회차('2026-08-31'), 안: 안, 우리글: '', 상태: 상태 }, 설,
    { 미리보기: true });
}

/* ═══ ㉠ 안 쓴 줄은 안 나간다 ═════════════════════════════════════════ */

test('★★ 우리 말이 없는 기사는 «편지에 안 나간다»', () => {
  assert.equal(C.편지에실릴까(기사(), false), false,
    '★★ 제목만 있는 기사가 나간다 — 유료 매체 제목을 그대로 옮기는 셈이다');
  assert.equal(C.편지에실릴까(기사({ 우리말: '우리 정리' }), false), true,
    '★ 우리 말을 썼는데도 안 나간다');
  assert.equal(C.편지에실릴까(기사({ 우리말: '   ' }), false), false,
    '★ 빈칸만 쓴 것을 «썼다»고 본다');
});

test('★★ 하나도 안 썼으면 주간노동뉴스 꼭지가 «통째로» 안 나간다', () => {
  const 편 = 편지({ news: [기사(), 기사(), 기사()] });
  assert.equal(편, null, '★★ 안 쓴 기사 셋이 그대로 나갔다 — 「그대로 전달」이다');
});

test('★ 여덟 건 가운데 «쓴 것만» 나간다', () => {
  const 안 = { news: [기사({ 우리말: '첫째정리' }), 기사(), 기사({ 우리말: '셋째정리' })] };
  const h = 편지(안).서식;
  assert.ok(h.indexOf('첫째정리') >= 0 && h.indexOf('셋째정리') >= 0, '★ 쓴 것이 안 나갔다');
  const 셈 = C.실림셈(안, '');
  assert.deepEqual(셈.표.news, { 실림: 2, 담김: 3 },
    '★ 화면 숫자가 편지와 다르다 — 「담았는데 왜 안 나가나」가 된다');
});

test('★★ 자료·판례는 그대로 나간다 — 우리 말을 요구하지 않는다', () => {
  /* 자료는 기관이 «공개하려고» 낸 것이고, 판결문은 저작물이 아니다.
     여기까지 막으면 편지에 실을 것이 거의 없어진다. */
  assert.equal(C.편지에실릴까({ 갈래: '자료', 제목: 'ㄱ' }, false), true,
    '★★ 기관 자료까지 막았다');
  assert.equal(C.편지에실릴까({ 갈래: '판례', 제목: 'ㄱ' }, false), true,
    '★★ 판례까지 막았다 — 판결문은 저작물이 아니다');
});

/* ═══ ㉡ 우리 말이 본문이다 ═══════════════════════════════════════════ */

test('★★ 우리 말이 있으면 «그것»이 실리고 원문 제목은 안 실린다', () => {
  const h = 편지({ news: [기사({ 우리말: '우리가 쓴 한 줄입니다' })] }).서식;
  assert.ok(h.indexOf('우리가 쓴 한 줄입니다') >= 0, '★ 우리 말이 안 실렸다');
  assert.ok(h.indexOf('원문제목입니다') < 0,
    '★★ 원문 제목이 함께 실렸다 — 그대로 옮기지 않겠다는 뜻이 무너진다');
  assert.ok(h.indexOf('원문 ↗') >= 0, '★ 원문으로 가는 길이 없다 — 출처를 감추는 셈이다');
});

test('★ 평문 몫에도 «우리 말»이 실린다 — 한쪽만 고치면 사람마다 다른 편지다', () => {
  const 편 = 편지({ news: [기사({ 우리말: '우리가 쓴 한 줄입니다' })] });
  assert.ok(편.본문.indexOf('우리가 쓴 한 줄입니다') >= 0 ||
            편.본문.indexOf('원문제목입니다') >= 0,
    '★ 평문에 아무것도 안 실렸다');
});

/* ═══ ㉢ 출처를 밝힌다 ═══════════════════════════════════════════════ */

test('★★ 꼭지 아래에 «참고: 매일노동뉴스» 가 붙는다', () => {
  const h = 편지({ news: [기사({ 우리말: '우리 정리' })] }).서식;
  assert.ok(h.indexOf('참고:') >= 0, '★★ 참고한 곳을 안 밝힌다 — 안 밝히는 것이 더 나쁘다');
  assert.ok(h.indexOf('매일노동뉴스') >= 0, '★★ 어디를 참고했는지 안 적는다');
  assert.ok(h.indexOf('푸른노무법인이 썼습니다') >= 0,
    '★ 누가 쓴 글인지 안 적는다 — 우리 글임을 밝혀야 우리 저작물이 된다');
});

test('여러 곳을 참고하면 «다» 적는다 — 한 곳만 적으면 나머지를 감춘 셈이다', () => {
  const h = 편지({ news: [
    기사({ 우리말: 'ㄱ', 언론사: '매일노동뉴스' }),
    기사({ 우리말: 'ㄴ', 언론사: '한국노동연구원' })] }).서식;
  assert.ok(h.indexOf('매일노동뉴스') >= 0 && h.indexOf('한국노동연구원') >= 0,
    '★ 참고한 곳 하나가 빠졌다');
});

/* ═══ ㉣ 이미 보낸 회차는 «그때 그대로» ═══════════════════════════════ */

test('★★ 이미 «보낸» 회차는 그때 나간 그대로 보인다 — 지난 회차가 사라지면 안 된다', () => {
  /* 그때는 우리말 칸이 없었다. 새 잣대를 들이대면 지난 회차를 다시 열 때
     주간노동뉴스가 «통째로» 사라진다 — 보낸 편지를 못 확인하게 된다. */
  const 안 = { news: [기사(), 기사()] };
  assert.equal(편지(안, '초안'), null, '(재기 값) 초안에서는 안 나간다');
  const 보낸것 = 편지(안, '발송');
  assert.ok(보낸것, '★★ 이미 보낸 회차가 통째로 비었다');
  assert.ok(보낸것.서식.indexOf('원문제목입니다') >= 0,
    '★★ 보낸 회차에서 기사가 사라졌다 — 그때 나간 편지를 확인할 길이 없다');
  assert.equal(C.편지에실릴까(기사(), true), true, '★ 보낸것 잣대가 안 먹는다');
});

/* ═══ ㉤ 판례는 «결과만» ═════════════════════════════════════════════ */

const 판례 = {
  갈래: '판례', 딱지: '[판례]',
  제목: '가'.repeat(180),
  인용: '대법원 2025다215010 (2026. 6. 25.)', 링크: 'https://www.law.go.kr/x',
  요지: '요지전문입니다'.repeat(20), 참조조문: '근로기준법 제94조 제1항',
  사건종류: '민사', 판결유형: '판결', 사건명: '임금'
};

test('★★ 판례에서 요지·참조조문이 «되살아나지 않는다»', () => {
  const h = 편지({ case: [C.판례다듬기(판례)] }).서식;
  assert.ok(h.indexOf('요지전문입니다') < 0,
    '★★ 요지 전문이 되살아났다 — 석 장이면 770자, 편지가 다섯 배가 된다');
  assert.ok(h.indexOf('참조조문') < 0, '★★ 참조조문이 되살아났다');
  assert.ok(h.indexOf('사건종류') < 0, '★ 사건종류가 되살아났다');
});

test('★★ 판시사항을 «두 줄»로 자르고, 잘렸다는 것을 숨기지 않는다', () => {
  const h = 편지({ case: [C.판례다듬기(판례)] }).서식;
  assert.ok(h.indexOf('…') >= 0, '★★ 잘랐는데 「…」이 없다 — 문장이 이상하게 끝난 것으로 읽힌다');
  const m = /가{20,}/.exec(h);
  assert.ok(m, '판시사항을 못 찾았다');
  assert.ok(m[0].length <= 110,
    '★★ 판시사항을 안 잘랐다 (' + m[0].length + '자) — 한 건이 다섯 줄을 먹는다');
});

test('★ 전문으로 가는 길이 있다 — 요지를 뺐으니 여기뿐이다', () => {
  const h = 편지({ case: [C.판례다듬기(판례)] }).서식;
  assert.ok(h.indexOf('전문 보기') >= 0, '★★ 전문을 볼 길이 없다');
  assert.ok(h.indexOf('대법원 2025다215010') >= 0, '★ 어느 판례인지 알 길이 없다');
});

test('★ 판례에도 «우리 말»을 쓰면 그것이 제목이 된다 — 자른 글보다 낫다', () => {
  const h = 편지({ case: [C.판례다듬기(Object.assign({}, 판례,
    { 우리말: '취업규칙을 불이익하게 바꾸려면 집단적 동의를 받아야 한다' }))] }).서식;
  assert.ok(h.indexOf('취업규칙을 불이익하게 바꾸려면') >= 0, '★ 우리 말이 안 쓰였다');
  assert.ok(!/가{20,}/.test(h), '★ 우리 말을 썼는데도 자른 판시사항이 함께 나온다');
});

/* ═══ ㉥ 화면이 «이어져» 있는가 ═══════════════════════════════════════ */

test('★★ 줄을 눌러 «우리 말로» 쓰는 창이 있다', () => {
  const 열기 = 함수몸(화면, '줄창열기');
  assert.ok(열기, '줄창열기 함수가 없다');
  assert.match(열기, /App\.줄창/, '★ 어느 줄을 열었는지 안 담는다');
  const 그리기 = 함수몸(화면, '줄창그리기');
  assert.ok(그리기, '줄창그리기 함수가 없다');
  assert.match(그리기, /rowW/, '★ 우리 말을 쓸 칸이 없다');
  assert.match(그리기, /본문을 옮기기/,
    '★ 쓰는 법(무엇이 안 되는지)을 창 안에 안 적었다 — 그것이 이 창의 절반이다');
  /* 그리는 쪽이 실제로 불러야 뜻이 있다 */
  assert.match(함수몸(화면, 'render'), /줄창그리기\(\)/, '★ 아무도 안 그린다');
  /* 줄에서 열 수 있어야 한다 */
  assert.match(함수몸(화면, '꼭지칸하나'), /줄창열기\(/, '★ 줄을 눌러도 안 열린다');
});

test('★★ 쓴 것을 «저장»한다 — 안 하면 새로 고칠 때 되돌아간다', () => {
  const 저장 = 함수몸(화면, '우리말저장');
  assert.ok(저장, '우리말저장 함수가 없다');
  assert.match(저장, /회차저장\(/, '★★ 화면만 바꾸고 저장을 안 한다');
  assert.match(저장, /delete /, '★ 비워서 되돌릴 길이 없다');
  assert.match(저장, /우리말 = /, '★ 담는 자리가 없다');
});

test('★ 목록에서 «썼는지» 바로 보인다 — 안 보이면 편지에서 찾게 된다', () => {
  const 칸 = 함수몸(화면, '꼭지칸하나');
  assert.match(칸, /wtag/, '★ 딱지가 없다');
  assert.match(칸, /아직 안 씀/, '★ 안 썼다는 것을 안 말한다 — 왜 안 나가는지 모른다');
});

test('★ 요약이 «몇 건만 썼는지» 말한다', () => {
  const 요약 = 함수몸(화면, '편지요약');
  assert.match(요약, /우리 말/, '★ 요약이 우리 말을 안 말한다');
  assert.match(요약, /안 나갑니다/, '★ 안 나간다는 것을 안 말한다');
});
