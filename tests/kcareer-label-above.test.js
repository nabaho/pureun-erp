/* 경력관리 — 라벨이 «위»에 있는 서식도 알아본다 (대표 지시 2026-09-06 「라벨위 찾기」)

   ■ 무엇이 문제였나
     값 칸의 «바로 왼쪽»만 보고 무슨 칸인지 판단했다. 그래서
         성명 | 생년월일 | 연락처 | 이메일     ← 라벨 줄
           · |    ·     |   ·    |   ·        ← 값 줄
     같은 «머리행형» 서식은 한 칸도 못 알아봤다. 기관 양식에 아주 흔한 모양이고,
     사전을 아무리 넓혀도 안 고쳐지는 «구조» 문제였다.

   ■ 실측 (흔한 서식 다섯 모양, 2026-09-06)
     A 왼쪽 라벨 2열 100% · B 4열 두 쌍 100% · C 머리행형 «0%» · D 특이한 말 60% ·
     E 목록에 「-」 0%  → 합계 54%
     이 고침 뒤 C 가 0% → 100%, 합계 54% → 85%.
     (D 는 사전 미스, E 는 자리표 문제라 여기서 다루지 않는다.) */
'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const M = require('../js/kcareer-formmap.js');
const H = require('../hwpx_gen.js');

function tbl(rows) { return H.tablePara(rows, H.cols(rows[0].map(() => 1 / rows[0].length))); }
const 값 = { fields: { name: '권형하', birth: '1975.01.07', phone: '010-0000-0000',
                      email: 'k@pureun.kr', org: '푸른노무법인', title: '대표' } };
const 짐작 = (rows) => M.guess(M.scan(tbl(rows)), 값).slots
  .filter((s) => s.guess).map((s) => s.row + ',' + s.col + '=' + s.guess);

test('★★ 라벨이 «위»에 있어도 알아본다 — 머리행형', () => {
  const g = 짐작([['성명', '생년월일', '연락처', '이메일'], ['', '', '', '']]);
  assert.deepEqual(g.sort(), ['1,0=name', '1,1=birth', '1,2=phone', '1,3=email'].sort(),
    '★ 이것이 0개였습니다 — 기관 양식에 가장 흔한 모양입니다');
});

test('★★ 왼쪽이 «먼저»다 — 둘 다 있으면 왼쪽이 그 칸을 가리킨다', () => {
  /* 「소속 | (값)」 처럼 왼쪽 라벨이 있는데 위에도 다른 라벨이 있으면 왼쪽을 따른다. */
  const g = 짐작([['성명', '생년월일'], ['소속', '']]);
  assert.ok(g.indexOf('1,1=org') >= 0, '왼쪽 「소속」을 따라야 합니다');
  assert.ok(g.indexOf('1,1=birth') < 0, '★ 위(생년월일)를 따르면 안 됩니다');
});

test('★★ 윗칸이 «사전이 아는 라벨»일 때만 인정한다', () => {
  /* 아무 글자나 받으면 윗줄의 «값»을 라벨로 착각해 엉뚱한 값이 박힌다. */
  const g = 짐작([['비고란입니다', '참고'], ['', '']]);
  assert.deepEqual(g, [], '★ 모르는 말을 라벨로 삼으면 안 됩니다');
});

test('★★ «바로 윗줄»만 본다 — 두 줄 위까지 올라가면 같은 값이 줄줄이 박힌다', () => {
  const g = 짐작([['성명', '생년월일'], ['권형하', '1975.01.07'], ['', '']]);
  assert.ok(g.every((x) => x.indexOf('2,') !== 0),
    '★ 셋째 줄(값 줄 아래)까지 성명·생년월일로 보면 안 됩니다: ' + JSON.stringify(g));
});

test('★★ 라벨 줄 자신은 «고칠 자리»가 아니다 — 서식 문구를 덮으면 안 된다', () => {
  /* 머리행형에서는 라벨끼리 옆에 붙어 있다(성명|생년월일). 빗장이 없으면
     「생년월일」이 «왼쪽이 성명이니 값 칸» 으로 오인되어 라벨 줄이 통째로 고칠 칸이 된다. */
  const slots = M.scan(tbl([['성명', '생년월일', '연락처'], ['', '', '']])).slots;
  const 라벨줄 = slots.filter((s) => s.row === 0);
  assert.deepEqual(라벨줄, [], '★ 라벨 줄에 자리가 생기면 서식 글자를 덮어씁니다');
});

test('★ 목록 표를 머리행형으로 오인하지 않는다', () => {
  /* 학력 표는 목록으로 잡혀야 한다 — 낱개 칸으로 흩어지면 한 줄씩 못 채운다. */
  const m = M.scan(tbl([['기 간', '학 교 명', '전 공', '학 위'], ['', '', '', ''], ['', '', '', '']]));
  assert.equal(m.lists.length, 1);
  assert.equal(m.lists[0].kind, 'edu');
  assert.equal(m.slots.length, 0, '목록 줄은 낱개 자리로 세지 않습니다');
});

test('★ 아직 못 하는 것 — 머리행형 «목록»은 첫 줄만 (알고 두는 한계)', () => {
  /* 「성명|소속|연락처」 처럼 목록 열쇠가 하나뿐이면 목록으로 안 잡힌다.
     그러면 머리행 바로 아래 «한 줄»만 채워진다. 여러 줄짜리는 아직 못 한다.
     ⚠ 이 검사는 «되게» 하려는 것이 아니라 한계를 적어 두는 것이다 —
       고칠 때 이 검사를 고쳐 쓰면 된다. */
  const g = 짐작([['성명', '소속', '연락처'], ['', '', ''], ['', '', '']]);
  assert.ok(g.some((x) => x.indexOf('1,') === 0), '첫 줄은 채워집니다');
  assert.ok(g.every((x) => x.indexOf('2,') !== 0), '둘째 줄은 아직 못 채웁니다');
});
