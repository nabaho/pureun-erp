'use strict';
/* ══════ 「가진 것」 칸을 세로로 맞춘다 (대표 지시 2026-08-30 「가진것 열 정리하고 순서도 정리해라」) ══════
   대표 화면에서 이렇게 보였다 —
     · 명함이 없는 줄만 「등록증 1」이 맨 앞으로 당겨져, 눈으로 세로로 훑을 수가 없다
     · 명함 수가 한 자리냐 두 자리냐에 따라 뒤엣것이 통째로 밀린다
     · 붉은 딱지는 「대표번…」 「대표자…」로 잘려 무엇이 빠졌는지 알 수 없다

   ■ 까닭
     ① 셋을 flex 로 «이어 붙였다» — 앞엣것이 없으면 뒤엣것이 당겨진다. 맞을 리가 없다
     ② 칸이 202px 인데 여백 24 를 빼면 178, 그중 명함·등록증 알약이 126 을 먹어
        정작 봐야 할 붉은 딱지에 54px 만 남았다 (「대표번호 없음」은 88px 이 필요하다)

   ■ 어떻게 고쳤나
     · 자리를 «셋으로 못 박았다»(grid). 없는 것도 빈 자리로 남긴다
     · 명함·등록증에서 알약을 벗겼다 — 알약 하나가 여백으로만 14px 을 먹고 있었다
     · 붉은 딱지에서 「없음」 두 글자를 빼고 ✕ 로 바꿨다 (24px 을 되찾는다)
     · 칸 폭을 실측대로 다시 나눴다

   ★ 여기서 못 박는 것 — «실측한 px 이 규칙이다»
     ① 자리가 셋이고, 앞 둘은 못 박은 px 이다
     ② 「✕ 대표번호」(실측 74px)가 «잘리지 않을» 만큼 칸이 넓다
     ③ 유형 딱지가 접히지 않는다 — 접히면 그 줄만 키가 커져 세로가 어긋난다
     ④ 줄 키가 줄마다 같다
   실행: node --test tests/cards-co-bits-col.test.js */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const SRC = fs.readFileSync(path.join(__dirname, '..', 'pu-cards.html'), 'utf8').replace(/\r\n/g, '\n');

/* 브라우저에서 진짜 글꼴로 잰 값들 (2026-08-30). 이 숫자가 이 파일의 «규칙»이다 —
   지금 폭이 얼마인가가 아니라, 이만큼은 있어야 안 잘린다는 뜻이다. */
const 실측 = {
  명함두자리: 40,      /* 「명함 12」 평문 */
  등록증두자리: 52,    /* 「등록증 12」 평문 */
  등록증없음: 62,      /* 「✕ 등록증」 알약 */
  대표번호없음: 74,    /* 「✕ 대표번호」 알약 — 한 칸만 빠진 경우 중 가장 길다 */
  칸여백: 24           /* .cotbl td 의 padding 10px 12px → 좌우 24 */
};

function bitsCols(){
  const m = SRC.match(/\.corow \.bits\{[^}]*grid-template-columns:([^;}]+)/);
  assert.ok(m, '★ .corow .bits 에 자리를 못 박지 않았다 — 이어 붙이면 줄마다 어긋난다');
  return m[1].trim().split(/\s+/);
}
function colWidths(){
  const at = SRC.indexOf('<colgroup><col style="width:34px">');
  assert.ok(at > 0, '기업정보 표의 colgroup 을 찾지 못했다');
  const seg = SRC.slice(at, SRC.indexOf('</colgroup>', at));
  return (seg.match(/width:(\d+)px/g) || []).map(x => Number(x.match(/\d+/)[0]));
}
const GAP = () => Number((SRC.match(/\.corow \.bits\{[^}]*gap:(\d+)px/) || [0, 5])[1]);

/* ── ① 자리가 셋이고, 앞 둘은 못 박혀 있다 ────────────────────────── */

test('★ 앞 두 자리는 «못 박은 px» 이다 — auto 면 수가 늘 때마다 뒤가 밀린다', () => {
  const c = bitsCols();
  assert.equal(c.length, 3, '★ 자리가 셋이 아니다: ' + c.join(' '));
  assert.match(c[0], /^\d+px$/, '★ 명함 자리가 안 박혔다 — 「명함 5」와 「명함 12」에서 뒤가 어긋난다');
  assert.match(c[1], /^\d+px$/, '★ 등록증 자리가 안 박혔다');
  assert.ok(Number(c[0].slice(0, -2)) >= 실측.명함두자리,
    '★ 명함 자리가 ' + c[0] + ' 다 — 두 자리 수(' + 실측.명함두자리 + 'px)가 잘린다');
  assert.ok(Number(c[1].slice(0, -2)) >= 실측.등록증없음,
    '★ 등록증 자리가 ' + c[1] + ' 다 — 「✕ 등록증」(' + 실측.등록증없음 + 'px)이 잘린다');
});

/* ── ② 붉은 딱지가 잘리지 않는다 ──────────────────────────────────── */

test('★ 한 칸만 빠진 곳의 붉은 딱지가 «온전히» 보인다 — 「대표번…」이면 만든 뜻이 없다', () => {
  /* 이것이 대표님이 화면에서 본 그것이다. 칸이 좁아 무엇이 빠졌는지 못 읽었다.
     ⚠ 「둘 이상」 빠진 곳은 잘려도 좋다 — 셋을 다 담으려면 147px 이 필요하고,
       그러자면 상호 칸을 그만큼 빼앗아야 한다. 자른 것은 말풍선에 남는다. */
  const c = bitsCols();
  const w = colWidths();
  /* ⚠ 2026-09-03: 서식이 «제 열»로 나가 칸이 하나 늘었다 — 뒤 자리가 하나씩 밀린다 */
  const 가진것 = w[7];
  const 남는폭 = 가진것 - 실측.칸여백
    - Number(c[0].slice(0, -2)) - Number(c[1].slice(0, -2)) - GAP() * 2;
  assert.ok(남는폭 >= 실측.대표번호없음,
    '★ 붉은 딱지에 ' + 남는폭 + 'px 만 남았다 — 「✕ 대표번호」는 '
    + 실측.대표번호없음 + 'px 이 필요하다. 가진 것 칸(' + 가진것 + 'px)을 넓히거나 앞 자리를 줄일 것');
});

test('★ 마지막 자리가 «남는 폭»을 먹되 넘치지 않는다 — minmax 의 0 이 규칙이다', () => {
  const c = bitsCols();
  assert.match(c[2], /minmax\(0,\s*1fr\)/,
    '★ 그냥 1fr 이면 알약이 제 폭을 우겨 칸을 넘고 옆 칸을 민다 (grid 의 기본 최소는 auto 다)');
});

/* ── ③ 딱지가 접히지 않는다 ───────────────────────────────────────── */

test('★ 유형 딱지가 «접히지 않는다» — 접힌 줄만 키가 커져 세로가 어긋난다', () => {
  /* 실제로 겪었다(2026-08-30): 유형 칸을 68→58px 로 줄였더니 「자문」이 「자/문」으로
     갈려 그 줄만 3px 커졌다. 세로로 맞추려던 일이 도리어 어긋나게 했다. */
  const m = SRC.match(/\.corow \.ty\{([^}]*)\}/);
  assert.ok(m, '.corow .ty 규칙을 찾지 못했다');
  assert.match(m[1], /white-space:nowrap/,
    '★ 접히면 그 줄만 키가 커진다 — 「세로로 정렬해서 볼 수 있게」가 무너진다');
  /* 접지 않기로 했으면 칸은 담을 만큼 넓어야 한다 — 아니면 이번엔 잘린다.
     ⚠ 여기 64 는 «딱지»만 잰 값이다. 2026-08-31 에 알았듯 이 칸의 진짜 최소는
       «머리글»(80px)이다 — 몸은 맞는데 머리가 두 줄로 접혔다.
       칸 폭의 임자는 tests/cards-co-name-cell.test.js 의 「모든 칸이 실측 최소만큼은
       넓다」 한 곳이다. 여기서는 «딱지가 들어가는가»만 본다. */
  assert.ok(colWidths()[4] >= 64,
    '★ 유형 칸이 ' + colWidths()[4] + 'px 다 — 딱지 40 + 여백 24 = 64 가 최소다(실측)');
});

test('★ 줄 키가 줄마다 «같다»', () => {
  assert.match(SRC, /\.cotbl tbody tr\{[^}]*height:\d+px/,
    '★ 유형이 빈 회사가 섞이면 줄이 3px 씩 들쭉날쭉해 눈이 세로로 못 내려간다');
});

/* ── ④ 사업자번호도 함께 재 보았다 ────────────────────────────────── */

test('사업자번호가 «온전히» 보인다 — 재 보니 이미 잘리고 있었다', () => {
  /* 실측 102px. 120 − 여백 24 = 96 이라 끝자리가 잘려 나가고 있었다(2026-08-30). */
  /* ⚠ 2026-09-03: 서식 열이 생겨 자리가 하나 밀렸다 */
  assert.ok(colWidths()[6] >= 102 + 실측.칸여백,
    '★ 사업자번호 칸이 ' + colWidths()[6] + 'px 다 — 「134-86-05772」 102 + 여백 24 가 최소다');
});
