/* ══════════════════════════════════════════════════════════════════════════
   ⑤-2 행정해석에 «자리 하나»
   ══════════════════════════════════════════════════════════════════════════
   ⚠⚠ 2026-09-07 대표 화면: 판례 칸 3건이 «전부 판례»로 나갔다.
     상한이 3인데 판례 후보가 4건이라, 해석은 차례가 오기 전에 잘렸다 —
     해석을 읽는 길을 새로 만들어 놓고도 편지에는 «한 번도» 안 실렸다.
   ★ 「담기는 것」과 「나가는 것」이 다르면, 만든 사람만 됐다고 여긴다. */

const 판딱 = (n) => ({ 갈래: '판례', 딱지: '[판례]', 제목: '판례 ' + n, 법원: '대법원' });
const 해딱 = (n) => ({ 갈래: '판례', 딱지: '[행정해석]', 제목: '해석 ' + n, 법원: '법제처' });
const 딱지들 = (거리) => C.자동으로담기({}, { 판례: 거리 }, 회)['case'].map((x) => x.딱지);

test('★★ 판례가 넘쳐도 행정해석 «한 자리»는 남는다', () => {
  const 몇 = C.꼭지찾기('case').몇개;
  const 거리 = [];
  for (let i = 0; i < 몇 + 2; i++) 거리.push(판딱(i));
  거리.push(해딱(1), 해딱(2));
  const 나온것 = 딱지들(거리);
  assert.equal(나온것.length, 몇);
  assert.ok(나온것.indexOf('[행정해석]') >= 0,
    '★★ 행정해석이 한 건도 안 실렸다 — 꼭지 이름이 거짓이 된다: ' + 나온것.join(' '));
  assert.ok(나온것.filter((x) => x === '[판례]').length >= 1, '판례가 통째로 밀려났다');
});

test('★ 판례가 «주인»이다 — 해석을 앞세우지 않는다', () => {
  const 거리 = [해딱(1), 판딱(1), 판딱(2), 판딱(3), 판딱(4)];
  assert.equal(딱지들(거리)[0], '[판례]', '해석이 맨 앞에 왔다');
});

test('★ 해석이 없는 주에는 판례가 «그 자리까지» 다 쓴다 — 빈 자리를 만들지 않는다', () => {
  const 몇 = C.꼭지찾기('case').몇개;
  const 거리 = [];
  for (let i = 0; i < 몇 + 2; i++) 거리.push(판딱(i));
  const 나온것 = 딱지들(거리);
  assert.equal(나온것.length, 몇, '해석이 없는데 자리를 비웠다');
  assert.ok(나온것.every((x) => x === '[판례]'));
});

test('판례가 없는 주에는 해석만 나간다', () => {
  assert.deepEqual(딱지들([해딱(1), 해딱(2)]), ['[행정해석]', '[행정해석]']);
});

