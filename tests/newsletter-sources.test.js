test('★ 보도자료에서는 목차를 «뽑지 않는다» — 없는 차례를 있다고 적지 않게', () => {
  /* ⚠ 보도자료 본문 첫 줄들은 「- 9월 14일부터 …」 같은 부제다.
       목차뽑기가 그것을 집어 편지에 「1. 체불청산, 산재예방 …」으로 실렸다(2026-09-07). */
  assert.equal(D.샘찾기('moel-news').목차없음, true);
  const 부제있는설명 = '- 체불청산, 산재예방 등 탁월한 성과\n- 24명, 28개 부서에 특별 승진';
  const 정책 = D.자료로만들기({ 일련번호: '1', 제목: 'ㄱ', 설명: 부제있는설명, 샘: 'moel-policy' });
  const 보도 = D.자료로만들기({ 일련번호: '1', 제목: 'ㄱ', 설명: 부제있는설명, 샘: 'moel-news' });
  assert.ok(정책.목차.length > 0, '정책자료실에서는 목차를 뽑아야 한다');
  assert.deepEqual(보도.목차, [], '★ 보도자료에서 부제를 목차로 집었다');
});

