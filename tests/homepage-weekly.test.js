'use strict';
/* 주간 뉴스레터 (대표 지시 2026-09-02 「공지사항은 뉴스레터와 같이 1주일에 1개씩」)
 *
 * ★ 왜 «날마다 모아 두었다가» 주 1회 내는가 —
 *   신문사 RSS 는 최근 50개만 준다. 2026-09-02 실측으로 그것이 «이틀치»뿐이었다
 *   (50개 = 8/30~9/1). 주 1회만 읽으면 「주간」이라 이름 붙이고 이틀치만 싣게 된다.
 *   그래서 날마다 제목·링크만 모아 두었다가 월요일에 한 장으로 낸다.
 *
 * 이 검사가 지키는 것 넷:
 *   ① 같은 기사를 두 번 싣지 않는다 (링크로 가린다)
 *   ② 모음이 끝없이 부풀지 않는다 (오래된 것은 턴다)
 *   ③ 지난 한 주 것만 싣는다 (지지난 주 것이 섞이면 뉴스레터가 아니다)
 *   ④ 실을 것이 없으면 «아무것도 만들지 않는다» — 빈 뉴스레터는 그 주 공지를 빈 껍데기로 만든다
 *
 * 실행: node --test tests/*.test.js
 * (이 환경의 node 는 --test 에 디렉터리 인자를 주면 죽는다. 반드시 glob 으로.)
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const R = path.join(__dirname, '..');
const B = require(path.join(R, 'functions', 'news-brief.js'));

const 기사 = (n, 날) => ({ 제목: '기사' + n, 링크: 'https://a.kr/' + n, 언론사: '매일노동뉴스', 모은날: 날 });

/* ══════ ① 모으기 — 같은 기사를 두 번 담지 않는다 ══════ */
test('★ 같은 링크는 다시 담지 않는다 — 같은 기사가 여러 날 RSS 에 남아 있다', () => {
  const 하루 = B.모으기({}, [기사(1), 기사(2)], '2026-09-01');
  assert.equal(하루.새로, 2);

  /* 이튿날 — 어제 것 하나가 아직 RSS 에 남아 있고, 새것이 하나 */
  const 이틀 = B.모으기(하루.모음, [기사(2), 기사(3)], '2026-09-02');
  assert.equal(이틀.새로, 1, '★ 어제 담은 기사를 또 담았습니다');
  assert.equal(Object.keys(이틀.모음).length, 3);
});

test('★ 파이어베이스가 못 삼키는 글자를 열쇠에 넣지 않는다', () => {
  const k = B.링크열쇠('https://a.kr/news/1.html#top?x=$1[2]');
  assert.ok(!/[.#$/[\]]/.test(k), '★ 열쇠에 . # $ / [ ] 가 남아 있습니다: ' + k);
  assert.ok(k.length > 0);
});

test('제목이나 링크가 없는 것은 담지 않는다', () => {
  const r = B.모으기({}, [{ 제목: '', 링크: 'https://a.kr/1' }, { 제목: '가', 링크: '' }, null], '2026-09-01');
  assert.equal(r.새로, 0);
});

/* ══════ ② 털기 — 모음이 끝없이 부풀지 않는다 ══════ */
test('★★ 오래된 것을 턴다 — 안 털면 모음이 해마다 부푼다', () => {
  const 모음 = {
    a: 기사(1, '2026-08-01'),   /* 한 달 전 */
    b: 기사(2, '2026-08-25'),
    c: 기사(3, '2026-09-01')
  };
  const 남은것 = B.오래된것털기(모음, '2026-09-02', 14);
  assert.ok(!남은것.a, '★ 한 달 전 것이 아직 남아 있습니다');
  assert.ok(남은것.b && 남은것.c, '★ 최근 것을 털어 버렸습니다');
});

/* ══════ ③ 고르기 — 지난 한 주 것만 ══════ */
test('★★ 지지난 주 것은 안 싣는다 — 섞이면 「주간」이 아니다', () => {
  const 모음 = {
    a: 기사(1, '2026-08-20'),   /* 지지난 주 */
    b: 기사(2, '2026-08-27'),   /* 지난 한 주 안 */
    c: 기사(3, '2026-09-02')
  };
  const 고른것 = B.주간뉴스고르기(모음, '2026-09-02', 7);
  const 제목들 = 고른것.map((x) => x.제목);
  assert.ok(!제목들.includes('기사1'), '★ 지지난 주 기사가 실렸습니다: ' + 제목들.join(','));
  assert.deepEqual(제목들, ['기사3', '기사2'], '★ 최신순이 아닙니다');
});

test('이레의 첫날도 «안»에 든다 — 하루가 조용히 빠지면 매주 하루씩 잃는다', () => {
  /* 9/2 기준 지난 이레 = 8/27 ~ 9/2 */
  const 고른것 = B.주간뉴스고르기({ a: 기사(1, '2026-08-27') }, '2026-09-02', 7);
  assert.equal(고른것.length, 1, '★ 이레의 첫날이 빠졌습니다');
});

/* ══════ ④ 뉴스레터 한 장 ══════ */
const 법령보기 = [{
  이름: '근로기준법', 구분: '법률', 고친결: '일부개정',
  공포일: '20260825', 시행일: '20270101', 부처: '고용노동부', 링크: '/law/근로기준법'
}];

test('★★ 실을 것이 없으면 «만들지 않는다» — 빈 뉴스레터는 그 주 공지를 빈 껍데기로 만든다', () => {
  assert.equal(B.주간브리핑([], [], '2026-09-02'), null);
  assert.equal(B.주간브리핑(null, null, '2026-09-02'), null);
});

test('뉴스만 있어도, 법령만 있어도 만든다', () => {
  assert.ok(B.주간브리핑([기사(1, '2026-09-01')], [], '2026-09-02'));
  assert.ok(B.주간브리핑([], 법령보기, '2026-09-02'));
});

test('★★ 제목에 «기간»이 든다 — 하루치가 아니라 한 주치임이 제목에서 보여야 한다', () => {
  const b = B.주간브리핑([기사(1, '2026-09-01')], 법령보기, '2026-09-02');
  assert.match(b.제목, /2026-08-27 ~ 2026-09-02/, '★ 제목이 기간을 안 밝힙니다: ' + b.제목);
  assert.match(b.본문, /2026-08-27 ~ 2026-09-02/);
});

test('★★ 「매일 아침」이라 말하지 않는다 — 실제로는 주 1회다', () => {
  const b = B.주간브리핑([기사(1, '2026-09-01')], 법령보기, '2026-09-02');
  /* 「매일노동뉴스」는 언론사 이름이라 그냥 «매일»만 막으면 애먼 것이 걸린다 */
  assert.ok(!/매일 아침/.test(b.본문), '★ 주 1회인데 「매일 아침」이라 적혀 있습니다');
  assert.match(b.본문, /매주 월요일/, '★ 언제 올라오는지 안 밝힙니다');
});

test('★★ 기사 «본문»은 싣지 않는다 — 남의 글이다', () => {
  const b = B.주간브리핑(
    [{ 제목: '기사', 링크: 'https://a.kr/1', 언론사: '매일노동뉴스', 본문: '여기가 기사 본문이다' }],
    [], '2026-09-02');
  assert.ok(!/여기가 기사 본문이다/.test(b.본문), '★ 기사 본문을 옮겼습니다');
  assert.match(b.본문, /제목과 링크만/, '★ 왜 제목만 있는지 안 밝힙니다');
});

/* ══════ 두 번 감싸지 않는다 ══════ */
test('★★ 링크를 «두 번» 감싸지 않는다 — 누르면 엉뚱한 곳으로 간다', () => {
  /* 실제로 그랬다. 법제처가 준 XML 은 `?OC=test&amp;target=law` 인데
     그대로 두고 다시 감싸 `&amp;amp;` 가 되었고, 브라우저는 그것을
     `&amp;target=law` 로 읽는다 — 그 법령이 안 나오는데 오류도 안 난다. */
  const 조각 = '<law><법령명한글>근로기준법</법령명한글>'
    + '<법령상세링크>/DRF/lawService.do?OC=test&amp;target=law&amp;MST=1</법령상세링크></law>';
  const 읽은것 = B.법령읽기(조각);
  assert.equal(읽은것[0].링크, '/DRF/lawService.do?OC=test&target=law&MST=1',
    '★ XML 이 감싼 것을 안 풀었습니다');

  const b = B.주간브리핑([], 읽은것, '2026-09-02');
  assert.ok(!/&amp;amp;/.test(b.본문), '★ 두 번 감쌌습니다 — 링크가 깨집니다');
  assert.match(b.본문, /OC=test&amp;target=law/, '★ 한 번은 감싸야 합니다');
});

test('★ 기사 제목의 &amp; 도 그대로 읽힌다 — 「A&amp;B 노조」가 아니라 「A&B 노조」', () => {
  const 조각 = '<item><title>A&amp;B 노동조합 &quot;합의&quot;</title>'
    + '<link>https://a.kr/1</link></item>';
  const 읽은것 = B.뉴스읽기(조각, '매일노동뉴스');
  assert.equal(읽은것[0].제목, 'A&B 노동조합 "합의"');
});

test('★ 풀기는 «한 번만» 푼다 — &amp;lt; 가 꺾쇠까지 되면 안 된다', () => {
  assert.equal(B.풀기('&amp;lt;script&amp;gt;'), '&lt;script&gt;');
});

test('★★ 꺾쇠가 새지 않는다 — 기사 제목에 <script> 가 들어와도', () => {
  const b = B.주간브리핑(
    [{ 제목: '<script>나쁜것</script>', 링크: 'https://a.kr/1"onerror="x', 언론사: '' }],
    [], '2026-09-02');
  assert.ok(!/<script>/.test(b.본문), '★ script 태그가 그대로 나갔습니다');
  assert.ok(!/"onerror="/.test(b.본문), '★ 따옴표가 빠져나가 속성이 되었습니다');
});

test('한 주치는 하루치보다 «많이» 싣는다 — 이레를 모았으니', () => {
  const 많은뉴스 = Array.from({ length: 20 }, (_, i) => 기사(i, '2026-09-01'));
  const 주 = B.주간브리핑(많은뉴스, [], '2026-09-02');
  const 하루 = B.브리핑(많은뉴스, [], '2026-09-02');
  const 셈 = (s) => (s.match(/<li>/g) || []).length;
  assert.ok(셈(주.본문) > 셈(하루.본문),
    '★ 한 주치가 하루치보다 적거나 같습니다 (주 ' + 셈(주.본문) + ' · 하루 ' + 셈(하루.본문) + ')');
});

/* ══════ ⑤ 실제로 그렇게 «돌고 있나» ══════ */
const IDX = fs.readFileSync(path.join(R, 'functions', 'index.js'), 'utf8');
/* 소스를 글자로 볼 때는 주석을 먼저 걷는다 — 잘 쓴 주석이 검사를 통과시킨다 */
const 알맹이 = IDX.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1 ');

test('★★ 뉴스레터는 «주 1회» 올라간다 — 날마다 올리면 공지가 뉴스 게시판이 된다', () => {
  const 자리 = 알맹이.indexOf('weeklyNewsBrief');
  assert.ok(자리 > 0, '★ 주간 뉴스레터를 올리는 곳이 없습니다');
  const 몸통 = 알맹이.slice(자리, 자리 + 3000);
  assert.match(몸통, /pubsub\s*\.\s*schedule\(\s*["'][^"']*monday/i,
    '★ 월요일에 도는 것이 아닙니다');
  assert.match(몸통, /timeZone\(\s*["']Asia\/Seoul/, '★ 서울 시각이 아닙니다');
});

test('★★ 모으는 일은 «날마다» 돈다 — 주 1회만 읽으면 이틀치밖에 못 싣는다', () => {
  const 자리 = 알맹이.indexOf('dailyNewsCollect');
  assert.ok(자리 > 0,
    '★ 날마다 모으는 곳이 없습니다. RSS 는 이틀치뿐이라, 모아 두지 않으면'
    + ' 「주간」이라면서 이틀치만 실립니다');
  const 몸통 = 알맹이.slice(자리, 자리 + 2000);
  assert.match(몸통, /pubsub\s*\.\s*schedule\(\s*["'][^"']*every day/i,
    '★ 날마다 도는 것이 아닙니다');
});

test('★★ 같은 주에 두 번 올리지 않는다', () => {
  const 자리 = 알맹이.indexOf('weeklyNewsBrief');
  const 몸통 = 알맹이.slice(자리, 자리 + 3000);
  assert.match(몸통, /lastWeek/,
    '★ 「이번 주에 이미 올렸나」를 안 봅니다 — 다시 돌면 같은 글이 두 번 실립니다');
});

test('★★ 법령을 «싣겠다는 만큼» 가져온다 — 가져오는 쪽이 목을 조르면 안 된다', () => {
  /* 실제로 그럴 뻔했다: 뉴스레터는 8건까지 싣겠다 해 두고, 거리를 모으는 쪽이
     5건에서 잘라 8건이 될 수 없었다. 조용해서 아무도 모를 자리다. */
  const 자리 = 알맹이.indexOf('weeklyNewsBrief');
  const 몸통 = 알맹이.slice(자리, 자리 + 3000);
  const m = /브리핑거리모으기\(\s*(\d+)\s*\)/.exec(몸통);
  assert.ok(m, '★ 주간치가 법령을 몇 건 가져올지 안 밝힙니다 — 하루치와 같은 5건에 잘립니다');
  assert.ok(Number(m[1]) >= 8,
    '★ 법령을 ' + m[1] + '건만 가져옵니다 — 한 주치인데 하루치보다 적거나 같습니다');
});

test('★★ 끄는 손잡이가 살아 있다 — 자동으로 나가는 글은 멈출 수 있어야 한다', () => {
  const 자리 = 알맹이.indexOf('weeklyNewsBrief');
  const 몸통 = 알맹이.slice(자리, 자리 + 3000);
  assert.match(몸통, /off\s*===\s*true/, '★ 끌 수가 없습니다');
});
