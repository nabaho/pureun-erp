/* ══════ ⑤ 오른쪽 상세 — 빈 칸이 자리를 안 먹는다 ══════ */
test('★★ 비어 있는 「메인 설명」은 «한 줄»이다', () => {
  const s = 함수(H, 'memberEdit');
  /* ★ «맨 앞에 나온 하나»만 보지 않는다 — 2026-09-03 에 삼항이 두 갈래로 갈라져
       (글이 있으면 rows="3" / 비었으면 rows="1") 소스에 두 번 나온다.
       앞엣것만 보면 «소스에 적힌 차례»가 검사를 좌우한다 — 그건 규칙이 아니다.
       규칙은 «비었을 때 한 줄로 접힌다»이므로, 나온 것 가운데 «가장 작은 것»을 본다. */
  const 자리 = s.indexOf('메인 설명');
  assert.ok(자리 >= 0, '★ 「메인 설명」 칸을 못 찾았다');
  const 뒤 = s.slice(자리, 자리 + 900);
  const 줄수들 = [...뒤.matchAll(/<textarea[^>]*rows="([^"]*)"/g)].map(m => m[1]);
  assert.ok(줄수들.length, '★ 「메인 설명」 칸을 못 찾았다');
  /* 글이 없으면 1줄, 있으면 더 크게 — 값을 박지 않고 «가리는지»만 본다 */
  assert.ok(줄수들.some(v => /\?/.test(v) || v === '1'),
    '★★ 비어 있을 때도 여러 줄을 차지한다 (rows=' + 줄수들.join('/') + ')'
    + ' — 비면 한 줄로 접고, 누르면 펴지게 할 것');
  assert.match(s, /onfocus/,
    '★ 접어 두었는데 «펴는 길»이 없다 — 눌러도 안 커지면 글을 쓸 수 없다');
});

