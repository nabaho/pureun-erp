/* 홈페이지 관리 화면 줄이기 — 「두 줄로 넘치지 않는다」 (대표 지적 2026-09-02)
 *
 * 대표: 「불필요한 셀이나 내용들을 간략하게 줄이고 셀안의 내용을 2줄 씩한부분은
 *        1줄로 정리하거나 할 수 있나」
 * 딱지 줄은 두 갈래를 드려 «㉯ 「같음」 딱지를 뺀다» 를 고르셨다.
 *
 * ★ 못 박는 것은 «글자»가 아니라 규칙이다 —
 *   자리가 넓어지면 2줄로 되돌리고 싶은 마음이 생기는 자리라, 규칙으로 막는다.
 *   (저장소 규칙: 표 한 칸은 한 줄. 「0」 같은 빈 값은 안 그린다.)
 *
 * 실행: node --test tests/*.test.js
 * (이 환경의 node 는 --test 에 디렉터리 인자를 주면 죽는다. 반드시 glob 으로.)
 */
const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const R = path.join(__dirname, '..');
const RAW = fs.readFileSync(path.join(R, 'pu-home.html'), 'utf8');
const DIFF = fs.readFileSync(path.join(R, 'js', 'pu-home-diff.js'), 'utf8');

/* 소스를 글자로 볼 때는 주석을 먼저 걷는다 — 잘 쓴 주석이 검사를 통과시킨다 */
function 알맹이(s) {
  return s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1 ');
}
const H = 알맹이(RAW);
const D = 알맹이(DIFF);

/* 함수 하나를 떼어 온다 — 다음 함수가 시작하는 곳까지.
   ★ 죽은 이름을 이름표로 쓰지 않는다(그러면 그 이름이 살아 있는 것으로 보인다). */
function 함수(src, 이름) {
  const i = src.indexOf('function ' + 이름);
  assert.ok(i >= 0, '★ ' + 이름 + ' 을 못 찾았다');
  const j = src.indexOf('\nfunction ', i + 5);
  const k = src.indexOf('\nasync function ', i + 5);
  const 끝 = Math.min(j < 0 ? src.length : j, k < 0 ? src.length : k);
  return src.slice(i, 끝);
}

/* ══════ ① 거르개 딱지 — 한 줄에 든다 ══════ */
test('★★ 「같음」 딱지를 만들지 않는다 (대표 결정 ㉯ — 여섯이 두 줄로 넘쳤다)', () => {
  const s = 함수(H, 'chipsHtml');
  /* 상태 딱지를 만드는 목록에 same 이 없어야 한다 */
  const m = /\[([^\]]*'pending'[^\]]*)\]/.exec(s);
  assert.ok(m, '★ 상태 딱지를 만드는 목록을 못 찾았다');
  assert.ok(m[1].indexOf("'same'") < 0,
    '★★ 「같음」 딱지가 되살아났다 — 여섯 개가 되면 두 줄로 넘친다.'
    + ' 되살리려면 딱지를 더 줄일 방법을 함께 가져올 것');
});

