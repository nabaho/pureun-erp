test('★★ 딱지 이름에 «괄호말»을 붙이지 않는다 — 그것이 줄을 넘치게 했다', () => {
  /* 「퇴사 (명부)」·「내릴 것 (퇴사)」·「내려감 (퇴사 완료)」가 딱지를 길게 만들었다.
     ★ 뜻을 지우는 것이 아니다 — STATUS_TEXT·OWN_LABEL 은 긴 이름 그대로 두고,
       딱지에서만 괄호말을 뗀다(안내 띠는 까닭까지 알려 줘야 하니까).

     ⚠ 처음에 이 검사를 「.chips 를 감기지 않게(nowrap) + 옆으로 구르게」로 썼다가 고쳤다 —
       .chips 안에는 「이름으로 찾기」 칸이 «같이» 들어 있어서, 감기를 끄면 그 칸이
       딱지와 한 줄로 짜부라진다. 규칙을 잘못 짚으면 고치면서 다른 것을 망가뜨린다. */
  assert.match(H, /function pillShort/,
    '★ 딱지 이름을 짧게 만드는 것이 없다 — 괄호말이 그대로 붙는다');

  const chips = 함수(H, 'chipsHtml');
  assert.match(chips, /pillShort\(/, '★★ 딱지 줄이 아직 긴 이름을 그대로 쓴다');

  const rows = 함수(H, 'rowsHtml');
  assert.match(rows, /pillShort\(/,
    '★★ 줄의 대조 딱지가 아직 「내릴 것 (퇴사)」로 길다 —'
    + ' 옆의 명부 딱지가 이미 「퇴사」라 «퇴사»가 한 줄에 두 번 적힌다');

  /* 짧게 만드는 규칙이 실제로 괄호말을 떼는지 — 글자를 박지 않고 «규칙»을 돌려 본다 */
  const fn = new Function('return ' + 함수(H, 'pillShort'))();
  assert.equal(fn('내릴 것 (퇴사)'), '내릴 것');
  assert.equal(fn('퇴사 (명부)'), '퇴사');
  assert.equal(fn('남김'), '남김', '★ 괄호말이 없는 이름을 건드렸다');
  assert.equal(fn(null), '', '★ 빈 값에서 터진다');
});

