test('★ 「글 번호」 칸이 그 줄에서 «가장 좁다» — 숫자 몇 자리다', () => {
  const s = 함수(H, 'memberEdit');
  const m = /flex: *0 *0 *(\d+)px[\s\S]{0,150}?글 번호/.exec(s)
         || /글 번호[\s\S]{0,150}?flex: *0 *0 *(\d+)px/.exec(s);
  assert.ok(m, '★ 글 번호 칸의 너비를 못 찾았다');
  const 글번호 = Number(m[1]);
  /* ★ 「100px 아래」를 박지 않는다 — 2026-09-03 에 라벨이 칸 «안»으로 들어갔다.
       라벨을 품어야 하니 상자는 그만큼 넓어야 한다(그 대신 라벨 줄 하나가 사라졌다).
       지켜야 하는 규칙은 «숫자 몇 자리에 넓은 자리를 주지 않는다»이고,
       그것은 «이름 칸보다 좁다»로 재는 것이 값을 박는 것보다 오래 산다. */
  const 이름 = /flex: *0 *0 *(\d+)px[\s\S]{0,80}?<b>이름<\/b>/.exec(s)
            || /<b>이름<\/b>[\s\S]{0,80}?flex: *0 *0 *(\d+)px/.exec(s);
  if (이름) {
    assert.ok(글번호 < Number(이름[1]),
      '★ 글 번호 칸(' + 글번호 + 'px)이 이름 칸(' + 이름[1] + 'px)보다 넓다'
      + ' — 숫자 몇 자리인데 이름보다 넓을 까닭이 없다');
  }
  assert.ok(글번호 <= 130,
    '★ 글 번호 칸이 ' + 글번호 + 'px 다 — 숫자 몇 자리에 너무 넓다 (라벨을 품어도 130px 안으로)');
});
