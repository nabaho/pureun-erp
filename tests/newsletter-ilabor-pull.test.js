test('★★ 서랍이 «꼭지를 밀지 않는다» — 떠 있는 창이다', () => {
  /* 대표 지시 2026-09-06: 「검토 내용이 아래로 내려가서 더이상 볼 수가 없다.
     근본적으로 해결할 수 있도록」
     ⚠ 예전에는 서랍을 꼭지 «위»에 끼워 넣었다. 그것이 제 키를 다 먹고 꼭지 넷을
       아래로 밀어, 판례·인사노무가 화면 밖으로 나갔다.
     ★ 칸 안에 넣는 한 «무엇을 더해도» 같은 일이 되풀이된다 — 그래서 떼어 냈다.
       이 검사가 다시 끼워 넣는 것을 막는다. */
  const 이번 = 함수몸(화면, '이번회차화면');
  assert.ok(!/노무사회서랍\(/.test(이번),
    '★ 서랍이 다시 칸 «안»으로 들어갔다 — 꼭지가 또 화면 밖으로 밀린다');
  assert.ok(/id="ilbox"/.test(화면), '★ 떠 있는 창 자리가 없다');
  const 붙임 = 화면.replace(/\s*\n\s*/g, '');
  assert.ok(/#ilbox\{[^}]*position:\s*fixed/.test(붙임),
    '★ 떠 있지 않다 — 흐름 안에 있으면 결국 무언가를 민다');
});

