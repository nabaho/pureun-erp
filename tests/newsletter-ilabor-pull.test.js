/* ═══ 화면이 줄었는가 ═══════════════════════════════════════════════ */

test('★ 담는 법이 «한 줄 띠»다 — 카드 셋이 세로로 자리를 먹지 않는다', () => {
  assert.ok(/\.ways\{display:flex/.test(화면.replace(/\s+/g, ' ').replace(/ \{/g, '{')) ||
            /\.ways\s*\{[^}]*display:\s*flex/.test(화면),
    '★ 담는 법이 아직 카드 격자다');
});

test('★ 한 꼭지가 길어도 «다른 꼭지를 밀어내지 않는다»', () => {
  /* 폭이 아니라 «키»가 까닭이었다 — 주간노동뉴스 8건이 첫 줄을 늘려
     판례·인사노무가 첫 화면 밖으로 밀렸다.
     ⚠ 값(px·vh)을 못 박지 않는다 — «한도가 있는가»만 본다.
     ⚠ 2026-09-08 부터 꼭지는 «탭»이다. 그러면 밀어낼 «다음 줄»이 아예 없다 —
       한 꼭지가 아무리 길어도 다른 꼭지는 탭줄에 그대로 있다.
       그래서 지킬 것이 둘로 줄었다: 탭줄이 얼려 있는가 · 칸이 줄어들며 구르는가. */
  const 붙임 = 화면.replace(/\s*\n\s*/g, '');
  /* ㉠ 탭줄은 얼린다 — 함께 구르면 훑는 동안 어느 꼭지인지 잃는다 */
  assert.ok(/\.colL>\.jartabs\{[^}]*flex:\s*0/.test(붙임),
    '★ 탭줄이 함께 구른다 — 긴 꼭지를 훑는 동안 다른 꼭지로 갈 길을 잃는다');
  /* ㉡ 칸 하나가 남은 자리를 다 쓰고, min-height:0 이 있어야 «줄어든다» */
  assert.ok(/\.colL>\.jarpanel\{[^}]*flex:\s*1/.test(붙임),
    '★ 꼭지 칸이 남은 자리를 안 채운다');
  assert.ok(/\.colL>\.jarpanel\{[^}]*min-height:\s*0/.test(붙임),
    '★ min-height:0 이 없다 — 칸이 안 줄어들어 넘친 만큼이 창 밖으로 밀려난다');
  /* ㉢ 넘치는 것은 꼭지 «안»에서 본다 — 잘려서 안 보이면 안 된다 */
  assert.ok(/\.jarpanel>\.jarbody\{[^}]*overflow-y:\s*auto/.test(붙임),
    '★ 넘친 것을 볼 길이 없다 — 잘려서 안 보인다');
});

