test('★ 화면이 그 까닭을 «실제로 보여 준다»', () => {
  const 알림 = 함수몸(화면, '빈꼭지알림');
  assert.ok(알림, '빈꼭지알림 함수가 없다');
  assert.ok(/Core\.빈꼭지까닭\(/.test(알림), '★ 까닭을 Core 에 안 물어본다');
  assert.ok(/서랍열기\(\)|길바꾸기\('ilabor'\)/.test(알림), '★ 채울 길로 가는 단추가 없다');
  /* ★ 안내는 «한 줄»이다 (대표 지시 2026-09-06 「아래로 내려가서 볼 수가 없다」).
       80자짜리 설명을 그대로 펴면 반쪽 폭에서 서너 줄이 되고, 빈 꼭지가 둘이면
       여덟 줄이 자리를 먹어 아래 꼭지가 화면 밖으로 밀린다. 까닭은 ⓘ 에 넣는다. */
  assert.ok(/nowrap/.test(알림), '★ 안내가 여러 줄로 펴진다 — 아래 꼭지를 밀어낸다');
  assert.ok(/tipwrap/.test(알림), '★ 까닭을 볼 길(ⓘ)이 없다 — 줄이기만 하면 왜 빈지 모른다');
  /* ⚠ 함수가 «있기만» 해서는 뜻이 없다 — 꼭지를 그리는 쪽이 실제로 불러야 한다 */
  /* ⚠ 2026-09-08 부터 꼭지는 «탭»이라 한 번에 하나를 그린다(꼭지칸하나).
       예전 이름(꼭지칸들)으로 찾으면 못 찾는다 — 부르는 자리를 따라간다. */
  const 칸들 = 함수몸(화면, '꼭지칸하나');
  assert.ok(칸들, '꼭지칸하나 함수가 없다');
  assert.ok(/빈꼭지알림\(/.test(칸들),
    '★ 빈 꼭지를 그릴 때 그 까닭을 안 부른다 — 만들어 놓고 안 쓴다');
});

