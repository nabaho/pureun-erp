'use strict';
/* 접속 자가진단이 «동기화가 끝난 뒤에» 센다 (대표 제보 2026-09-07)
 *
 * ★ 무슨 일이 있었나
 *   「이알피 로그인 중 데이터가 변동된 것 같다는 문구가 나왔다」 —
 *   컨설팅 건수가 지난 접속보다 크게 줄었다는 경고였다. 거짓 경보였다.
 *
 * ★ 까닭
 *   점검이 «8초»에 셌는데, 초기 동기화 완료 표시(_fbSynced)는 늦으면 «12초»에 켜진다.
 *   서버에서 아직 다 못 받은 localStorage 를 세고 「줄었다」고 외친 것이다.
 *
 * ★★ 이 거짓 경보가 왜 나쁜가
 *   딸린 안내가 「서버백업에서 복원하세요」였다. 그 말을 믿고 복원하면
 *   «멀쩡한 최신 자료를 옛 백업으로 되돌린다» — 없던 손실을 경보가 만들어 낸다.
 */
const fs = require('fs');
const path = require('path');
const test = require('node:test');
const assert = require('node:assert');

const SRC = fs.readFileSync(path.join(__dirname, '..', 'pu-erp.html'), 'utf8');
const 대목 = SRC.slice(SRC.indexOf('접속 시 자가진단'),
                      SRC.indexOf('접속 시 자가진단') + 4200);

test('★★ 자가진단이 «동기화 완료»를 보고 센다 — 8초 붙박이로 세지 않는다', () => {
  assert.ok(/_fbSynced/.test(대목),
    '★ 동기화 완료 표시를 안 보면, 서버에서 덜 받은 상태를 「줄었다」로 읽습니다.\n'
    + '  _fbSynced 는 늦으면 12초에 켜지는데 점검이 8초에 세고 있었습니다.');
  assert.ok(!/\}, 8000\);/.test(대목),
    '★ 8초 붙박이로 돌아가면 안 됩니다 — 동기화가 그 안에 끝난다는 보장이 없습니다');
});

test('★ 동기화가 끝나지 않아도 «언젠가는» 센다 — 오프라인이면 영영 안 켜진다', () => {
  assert.ok(/기다린횟수|\battempt|\btries\b/.test(대목),
    '기다리는 횟수에 상한이 있어야 합니다 — 없으면 오프라인에서 점검이 영영 안 돕니다');
});

test('★★ 경고 안내가 «복원»을 앞세우지 않는다 — 거짓 경보 한 번에 최신 자료를 잃는다', () => {
  const at = SRC.indexOf('데이터가 지난 접속보다 크게 줄었습니다');
  assert.ok(at > 0, '급감 경고 문구를 못 찾았습니다');
  const 안내 = SRC.slice(at, at + 700);
  const 새로고침 = 안내.indexOf('새로고침');
  const 복원 = 안내.indexOf('복원');
  assert.ok(새로고침 > 0, '먼저 다시 보라는 말이 있어야 합니다');
  assert.ok(복원 > 0, '정말 줄었을 때의 길도 남아 있어야 합니다');
  assert.ok(새로고침 < 복원,
    '★ 「복원」이 「새로고침」보다 앞에 오면, 동기화가 늦었을 뿐인 사람이\n'
    + '  멀쩡한 최신 자료를 옛 백업으로 되돌립니다 — 없던 손실이 생깁니다');
  assert.ok(/복원하지 마/.test(안내),
    '숫자가 돌아오면 복원하지 말라는 말이 있어야 합니다');
});

test('⚠ 동기화 전 «서버 쓰기 막기»는 그대로다 — 자료를 지키는 진짜 장치다', () => {
  assert.ok(/if\(!_fbSynced\)\{[\s\S]{0,300}?서버 쓰기 보류/.test(SRC),
    '★ 이 장치가 있어서 이번 거짓 경보로도 자료가 안 지워졌습니다. 빼지 마십시오.');
});

test('⚠ 서버 건수 대비 급감 차단도 그대로다', () => {
  assert.ok(/옛 데이터로 판단, 서버 푸시 차단/.test(SRC),
    '이 기기가 서버보다 훨씬 적을 때 덮어쓰지 못하게 막는 장치입니다');
});
