/* 소스에서 «주석만» 걷어 낸다 — 글자로 보는 검사가 반드시 먼저 쓰는 것
   ═══════════════════════════════════════════════════════════════════════════
   ★ 왜 필요한가 — 이 저장소는 주석에 «까닭»을 길게 적는다. 그래서 글자로 보는
     검사가 주석을 안 걷으면, 잘 쓴 주석이 검사를 통과시킨다.
     예: 「⚠ bulk=batchId 만 고른다」라고 적어 두면, 정작 코드에서 그 거르기를
     빼도 검사가 통과한다 (tests-must-strip-comments).

   ★★ 왜 «각자» 쓰지 않고 여기 한 자리에 두나 — 2026-09-05 에 실제로 당했다.
     검사 파일마다 걷는 부품을 하나씩 베껴 두었는데, 그것이 «정규식 리터럴»을
     몰랐다. `replace(/'/g, …)` 처럼 정규식 안에 따옴표가 있으면 그때부터
     글자열 안이라고 착각해서, 그 뒤의 주석을 하나도 못 걷었다.
     걷은 줄 알았는데 안 걷혀서, 이빨이 있는 줄 알았던 검사 넷이 실은 없었다.
     한 자리에 두면 한 번 고치면 다 고쳐진다.

   ⚠ 완전한 파서가 아니다. «주석을 지우는 것»만 제대로 하면 된다:
     ① 글자열('…' "…" `…`) 안은 건드리지 않는다
     ② 정규식(/…/) 안도 건드리지 않는다 — 여기가 예전에 틀린 자리다
     ③ 벗어남표(\)는 통째로 넘긴다 */
'use strict';

/* 앞의 «뜻 있는 글자»가 이것들이면 다음 「/」는 나눗셈이 아니라 정규식이다.
   (값이 끝난 자리 뒤의 「/」만 나눗셈이다 — 이름·숫자·닫는 괄호 뒤) */
const 정규식앞 = '(,=:[!&|?{};+-*%~^<>\n\r\t ';

function 주석걷기(원본) {
  const s = String(원본 == null ? '' : 원본);
  let 나옴 = '';
  let i = 0;
  let 앞글자 = '';        /* 바로 앞의 «뜻 있는» 글자 (공백 아님) */

  while (i < s.length) {
    const c = s[i], 다음 = s[i + 1];

    /* 벗어남표는 통째로 */
    if (c === '\\') { 나옴 += s.slice(i, i + 2); i += 2; continue; }

    /* 여러 줄 주석 */
    if (c === '/' && 다음 === '*') {
      const 끝 = s.indexOf('*/', i + 2);
      i = 끝 < 0 ? s.length : 끝 + 2;
      나옴 += ' ';
      continue;                          /* 앞글자는 그대로 둔다 — 주석은 뜻이 없다 */
    }

    /* 한 줄 주석 */
    if (c === '/' && 다음 === '/') {
      const 끝 = s.indexOf('\n', i);
      i = 끝 < 0 ? s.length : 끝;
      나옴 += ' ';
      continue;
    }

    /* 글자열 — 그대로 옮긴다 */
    if (c === '"' || c === "'" || c === '`') {
      let j = i + 1;
      while (j < s.length) {
        if (s[j] === '\\') { j += 2; continue; }
        if (s[j] === c) { j++; break; }
        j++;
      }
      나옴 += s.slice(i, j);
      i = j; 앞글자 = c;
      continue;
    }

    /* ★ 정규식 리터럴 — 여기가 예전에 빠져 있던 자리다.
         안에 따옴표가 들어 있으면(예: /['"]/g) 글자열로 착각해 그 뒤가 통째로 어긋난다. */
    if (c === '/' && (앞글자 === '' || 정규식앞.indexOf(앞글자) >= 0)) {
      let j = i + 1, 대괄호 = false, 닫힘 = false;
      while (j < s.length) {
        const d = s[j];
        if (d === '\\') { j += 2; continue; }
        if (d === '\n') break;                    /* 한 줄을 넘으면 정규식이 아니다 */
        if (d === '[') 대괄호 = true;
        else if (d === ']') 대괄호 = false;
        else if (d === '/' && !대괄호) { j++; 닫힘 = true; break; }
        j++;
      }
      if (닫힘) {
        while (j < s.length && /[a-z]/.test(s[j])) j++;   /* g·i·m 같은 꼬리표 */
        나옴 += s.slice(i, j);
        i = j; 앞글자 = '/';
        continue;
      }
      /* 안 닫혔으면 정규식이 아니다 — 그냥 한 글자로 흘려보낸다 */
    }

    나옴 += c;
    if (!/\s/.test(c)) 앞글자 = c;
    i++;
  }
  return 나옴;
}

/* 이름 붙은 함수 하나의 «몸»만 떼어 온다 (중괄호를 센다).
   여러 검사가 같은 일을 하고 있어 여기 모은다. */
function 함수몸(소스, 이름) {
  const 시작 = 소스.indexOf('function ' + 이름 + '(');
  if (시작 < 0) return null;
  const 열림 = 소스.indexOf('{', 시작);
  if (열림 < 0) return null;
  let 깊이 = 0;
  for (let i = 열림; i < 소스.length; i++) {
    if (소스[i] === '{') 깊이++;
    else if (소스[i] === '}') { 깊이--; if (깊이 === 0) return 소스.slice(시작, i + 1); }
  }
  return null;
}

module.exports = { 주석걷기, 함수몸 };
