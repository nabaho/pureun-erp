/* ㅁ 로 고른다 — 「이번 편지에 실을까」 (대표 지시 2026-09-08)
   ═══════════════════════════════════════════════════════════════════════════
   「주간, 고용, 판례 인사 등 각각의 화면으로 각각의 내용을 선택할 수 있게
    탭을 다시 정렬해라 그리고 골라서 빼거나 넣을 수 있게 하려면 ㅁ 로 체크하게 해달라」

   ★ ✕(빼기)와 «뜻이 다르다» — ✕ 는 목록에서 아예 없애고, ㅁ 는 목록에 두고
     이번 편지에서만 뺀다. 껐다 켰다 하실 것이라 갈랐다.

   ⚠ 이 검사가 지키는 것
     ① 칸이 없으면 «실린다» — 새 칸 하나 때문에 옛 회차가 통째로 비면 안 된다
     ② 걸러내는 자리가 «한 곳» — 편지·평문·첨부·셈이 저마다 거르면 어긋난다
     ③ 화면이 «저장»까지 한다 — 안 하면 새로 고칠 때 되돌아가고, 그 사이에 보내면
        화면에서 뺀 줄이 편지에 실려 나간다
     ④ 꺼진 줄을 «감추지 않는다» — 사라지면 왜 안 나가는지도, 다시 켤 길도 없다 */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { 주석걷기, 함수몸 } = require('./helpers/strip-comments.js');

const 뿌리 = path.join(__dirname, '..');
const C = require('../js/pu-news-core.js');
const T = require('../js/pu-news-tpl.js');
const 화면 = 주석걷기(fs.readFileSync(path.join(뿌리, 'pu-news.html'), 'utf8'));

/* ⚠ 2026-09-08 부터 기사는 «우리 말»이 있어야 편지에 나간다(대표 지시 —
     매일노동뉴스를 그대로 옮기면 안 된다). 그래서 본보기에도 우리말을 둔다 —
     없으면 ㅁ 와 상관없이 안 실려, 이 파일이 재려던 «ㅁ» 규칙이 헛돈다. */
const 켠것 = { 갈래: '기사', 제목: '실리는기사제목', 우리말: '실리는기사제목 — 우리 정리',
  링크: 'https://x/1', 언론사: '매일노동뉴스' };
const 끈것 = { 갈래: '기사', 제목: '빠지는기사제목', 우리말: '빠지는기사제목 — 우리 정리',
  링크: 'https://x/2', 언론사: '매일노동뉴스', 안실음: true };

/* ═══ ① 칸이 없으면 «실린다» ═══════════════════════════════════════ */

test('★★ 칸이 없는 줄은 «실린다» — 옛 회차가 통째로 비면 안 된다', () => {
  assert.equal(C.실릴까({ 제목: 'x' }), true,
    '★ 안실음 칸이 없는 줄을 뺀다 — 여태 담아 둔 회차가 한 줄도 안 나간다');
  assert.equal(C.실릴까({ 제목: 'x', 안실음: false }), true);
  assert.equal(C.실릴까({ 제목: 'x', 안실음: true }), false, '★ 끈 줄을 싣는다');
  assert.equal(C.실릴까(null), false);
});

test('실릴것만 — 끈 줄만 빠지고 나머지는 «그대로»다', () => {
  const r = C.실릴것만({ news: [켠것, 끈것], policy: [끈것], case: [] });
  assert.equal(r.news.length, 1);
  assert.equal(r.news[0].제목, '실리는기사제목');
  assert.equal(r.policy.length, 0);
  assert.deepEqual(r.case, []);
});

test('실릴것만 — 원본을 «고치지 않는다»', () => {
  /* 화면이 들고 있는 그 자료다. 여기서 지우면 목록에서도 사라진다. */
  const 안 = { news: [켠것, 끈것] };
  C.실릴것만(안);
  assert.equal(안.news.length, 2, '★ 원본에서 줄을 지웠다 — 목록에서도 사라진다');
  assert.equal(안.news[1].안실음, true, '★ 원본의 칸을 건드렸다');
});

test('★ 실림셈 — 꼭지마다 «실릴 것 / 담긴 것»', () => {
  const s = C.실림셈({ news: [켠것, 끈것, 켠것], policy: [끈것] }, '');
  assert.deepEqual(s.표.news, { 실림: 2, 담김: 3 });
  assert.deepEqual(s.표.policy, { 실림: 0, 담김: 1 });
  assert.equal(s.총실림, 2);
  assert.equal(s.총담김, 4);
});

test('★ 우리 글도 «한 건»으로 센다 — 그것만 있는 주가 0건으로 보이면 안 된다', () => {
  const 빈 = C.실림셈({}, '');
  const 글 = C.실림셈({}, '이번 주 한마디');
  assert.equal(빈.총실림, 0);
  assert.equal(글.총실림, 1, '★ 우리 글만 쓴 주가 «0건»으로 보인다 — 못 보낸다고 막힌다');
  assert.equal(C.실림셈({}, '   ').총실림, 0, '빈칸만 쓴 것은 글이 아니다');
});

/* ═══ ② 걸러내는 자리가 «한 곳» ═══════════════════════════════════ */

test('★★ 편지와 평문 «둘 다»에서 빠진다 — 한쪽만 거르면 사람마다 다른 편지가 간다', () => {
  const 편 = T.편지짓기({ 회차: { 이름: '9월 1주차', 기간: '…', 열쇠: '2026-09-w1' },
    안: { news: [켠것, 끈것] }, 우리글: '' }, {}, { 미리보기: true });
  assert.ok(편.서식.indexOf('실리는기사제목') >= 0, '★ 켠 줄이 서식에 없다');
  assert.ok(편.서식.indexOf('빠지는기사제목') < 0, '★★ 끈 줄이 서식에 실렸다');
  assert.ok(편.본문.indexOf('실리는기사제목') >= 0, '★ 켠 줄이 평문에 없다');
  assert.ok(편.본문.indexOf('빠지는기사제목') < 0,
    '★★ 끈 줄이 평문에 실렸다 — 서식을 못 읽는 프로그램에서만 나타나는 탈이다');
});

test('★★ 첨부도 «함께» 빠진다 — 편지에 없는 자료의 파일만 딸려 가면 안 된다', () => {
  const 자료 = { 갈래: '자료', 제목: 'a', 파일이름: 'a.pdf', 파일크기: 1000,
    파일자리: 'ilabor/1/a.pdf' };
  assert.equal(C.첨부모으기({ policy: [자료] }).파일들.length, 1, '(재기 값)');
  const 끈자료 = Object.assign({}, 자료, { 안실음: true });
  assert.equal(C.첨부모으기({ policy: [끈자료] }).파일들.length, 0,
    '★★ 편지에서 뺀 자료의 파일이 첨부로 붙는다 — 받는 분이 무슨 첨부인지 모른다');
  assert.equal(C.첨부모으기({ policy: [끈자료] }).넘친것.length, 0,
    '★ 뺀 것을 「넘쳤다」고 알린다 — 한도 탈로 오해한다');
});

test('★ 편지짓기가 «부르는 쪽»에 거르기를 맡기지 않는다', () => {
  /* 미리보기·시험·진짜 셋이 부른다. 부르는 쪽마다 거르면 하나가 빠지고,
     그러면 화면에서 뺀 줄이 «진짜 편지에만» 실려 나간다. */
  const 몸 = 함수몸(주석걷기(fs.readFileSync(path.join(뿌리, 'js', 'pu-news-tpl.js'), 'utf8')),
    '편지짓기');
  assert.ok(몸, '편지짓기를 못 찾았다');
  assert.match(몸, /Core\.실릴것만/, '★ 편지짓기가 스스로 안 거른다');
});

/* ═══ ③ 화면 — 탭과 ㅁ 가 «이어져» 있는가 ═════════════════════════ */

test('★★ ㅁ 를 누르면 «저장»한다 — 안 하면 새로 고칠 때 되돌아간다', () => {
  const 몸 = 함수몸(화면, '실음바꾸기');
  assert.ok(몸, '실음바꾸기 함수가 없다');
  assert.match(몸, /회차저장\(/,
    '★★ 화면만 바꾸고 저장을 안 한다 — 그 사이에 보내면 뺀 줄이 편지에 실린다');
  assert.match(몸, /Core\.실릴까/, '★ 판단을 화면에서 두 벌로 짰다');
  /* 켜기와 끄기가 «둘 다» 되어야 한다 — 한 번 끄면 못 켜면 ✕ 와 다를 것이 없다 */
  assert.match(몸, /delete /, '★ 다시 켤 길이 없다 — 한 번 끄면 되돌릴 수 없다');
  assert.match(몸, /안실음 = true/, '★ 끄는 길이 없다');
});

test('★ 「모두 싣기 / 모두 빼기」도 저장하고, 무엇을 했는지 말한다', () => {
  const 몸 = 함수몸(화면, '꼭지모두');
  assert.ok(몸, '꼭지모두 함수가 없다');
  assert.match(몸, /회차저장\(/, '★ 저장을 안 한다');
  assert.match(몸, /toast\(/, '★ 무엇을 했는지 말하지 않는다');
  assert.match(몸, /목록에는 그대로/,
    '★ 「목록에서 지운 것이 아니다」를 안 말한다 — 다 사라진 줄로 보신다');
});

test('★★ 꺼진 줄을 «감추지 않는다» — 사라지면 다시 켤 길이 없다', () => {
  const 몸 = 함수몸(화면, '꼭지칸하나');
  assert.ok(몸, '꼭지칸하나 함수가 없다');
  /* 끈 줄도 그린다 — 거르고 그리면 화면에서 사라진다 */
  assert.ok(!/실릴것만|filter\(Core\.실릴까\)/.test(몸),
    '★★ 꺼진 줄을 화면에서 걸러 낸다 — 왜 안 나가는지도, 다시 켤 길도 없어진다');
  assert.match(몸, /offtag|안 실림/, '★ 꺼진 줄에 딱지가 없다 — 눈으로 구별할 수 없다');
  assert.match(몸, /type="checkbox"/, '★ ㅁ 가 없다');
  assert.match(몸, /실음바꾸기\(/, '★ ㅁ 를 눌러도 아무 일이 안 난다');
  /* ✕ 는 그대로 남아 있어야 한다 — 뜻이 다른 두 길이다 */
  assert.match(몸, /빼기\(/, '★ ✕(목록에서 아예 빼기)가 사라졌다');
});

test('★ 꺼진 줄이 «흐리게» 보인다 — 딱지에 취소선이 겹치지 않는다', () => {
  assert.match(화면, /\.item\.off/, '★ 꺼진 줄 꾸밈이 없다');
  const i = 화면.indexOf('.offtag{');
  assert.ok(i > 0, '.offtag 규칙이 없다');
  const 규칙 = 화면.slice(i, 화면.indexOf('}', i));
  assert.match(규칙, /display:\s*inline-block/,
    '★ 취소선이 딱지까지 그어진다 — 물려 내려오는 것은 자식이 끌 수 없다');
});

/* ═══ ④ 「실린 것」 숫자가 «켠 것»을 센다 ═════════════════════════ */

test('★★ 머리줄의 「실린 것」은 «ㅁ 를 켠 것»이다', () => {
  /* 담긴 수를 세면 ㅁ 를 다 꺼 놓고도 「15건 실렸다」로 보이고,
     빈 뉴스레터가 그 숫자를 믿고 나간다. */
  const 몸 = 함수몸(화면, '이번회차화면');
  assert.ok(몸, '이번회차화면을 못 찾았다');
  assert.match(몸, /Core\.실림셈/, '★ 실림셈을 안 쓴다');
  /* ⚠ 「실림셈을 쓰나」만 보면 이빨이 없다 — 총담김으로 바꿔도 통과했다.
       «어느 칸을 쓰는가»를 본다. */
  const m = /const\s+실린수\s*=\s*([^;]+);/.exec(몸);
  assert.ok(m, '실린수를 정하는 줄을 못 찾았다');
  assert.match(m[1], /총실림/,
    '★★ 담긴 수를 센다 — ㅁ 를 다 꺼 놓고도 「15건 실렸다」로 보이고, 빈 편지가 그 숫자를 믿고 나간다');
  assert.ok(!/총담김/.test(m[1]), '★★ 실린 수에 뺀 것까지 센다: ' + m[1].trim());
});

test('★★ 탭에 «실릴 것»이 눈에 보인다 — 도움말에만 있으면 안 보인다', () => {
  /* ⚠ 처음에는 「꼭지탭줄에 실림이 어딘가 있나」로 적었더니, 보이는 숫자를
       담긴 수로 바꿔도 통과했다 — title 안에 남아 있었기 때문이다.
       마우스를 올려야 보이는 것은 «보이는» 것이 아니다. */
  const 탭 = 함수몸(화면, '꼭지탭줄');
  const m = /<span class="n">([\s\S]*?)<\/span>/.exec(탭);
  assert.ok(m, '★ 탭에 숫자 칸이 없다');
  assert.match(m[1], /실림/, '★★ 보이는 숫자가 «실릴 것»을 안 말한다: ' + m[1].trim());
  assert.match(m[1], /담김/, '★ 보이는 숫자가 «담긴 것»을 안 말한다: ' + m[1].trim());
});
