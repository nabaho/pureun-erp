/* 기업정보함 — 종료·해지된 거래처 배지 문구.
   실행: node --test tests/*.test.js

   대표 지시 2026-08-11: "사업자 등록증에 담당 아래에 퇴사가 아닌 계약해지로 표시해달라."

   이 배지는 **업체**의 상태(업체관리에서 종료·해지·폐업)를 말한다. 그런데 명함 줄에
   「퇴사」라고 적으면 **그 사람이 회사를 나간 것**으로 읽힌다 — 전혀 다른 말이다.
   대표가 쓰는 말(폴더 이름도 「계약해지」)에 맞춘다. */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const app = fs.readFileSync(path.join(__dirname, '..', 'pu-cards.html'), 'utf8');

/* ⚠ 이 검사는 **뜻만** 못 박는다 — 배지 모양은 바뀐다.
   2026-08-11: 칸을 컴팩트하게 줄이면서 「🚪 계약해지」 글자가 문패 하나(🚪)로 줄고
   「계약해지」는 마우스 설명으로 옮겨 갔다. 모양을 못 박아 두었더니 그때 검사가
   깨졌다. 지켜야 할 것은 **「퇴사」라고 쓰지 않는 것**과 **어디든 계약해지라고
   읽을 수 있는 것**이다. */
test('종료·해지 거래처를 「퇴사」라고 적지 않는다', () => {
  /* ⚠ 파일 첫 🚪 는 로그아웃 단추다 — 배지 클래스로 정확히 집는다 */
  const i = app.indexOf('class="mgq"');
  assert.ok(i > 0, '종료·해지 배지를 찾을 수 없습니다');
  const badge = app.slice(i - 500, i + 200);
  assert.ok(!/퇴사<|퇴사」로 표시|>🚪 퇴사</.test(badge),
    '「퇴사」로 적혀 있습니다 — 사람이 회사를 나간 것으로 읽힙니다');
  assert.match(badge, /계약해지/, '어디에도 「계약해지」라고 읽을 곳이 없습니다');
});

test('배지 설명에 무엇을 보고 붙인 것인지 남긴다', () => {
  /* 「계약해지」만 보이면 폐업한 업체도 해지로 읽힌다 — 설명에 셋을 다 적어 둔다. */
  /* ⚠ 파일 첫 🚪 는 로그아웃 단추다 — 배지 클래스로 정확히 집는다 */
  const i = app.indexOf('class="mgq"');
  const around = app.slice(Math.max(0, i - 500), i + 200);
  assert.match(around, /종료·해지·폐업/, '무엇을 보고 붙인 배지인지 설명이 없습니다');
});

test('「업체퇴사」 폴더 이름은 건드리지 않는다', () => {
  /* ⚠ 이 이름으로 만들어진 폴더가 이미 실제로 있고 그 안에 명함이 들어 있다.
     코드에서 이름을 바꾸면 앱이 없는 폴더를 찾아 **새 빈 폴더를 만들고**,
     기존 폴더의 명함은 주인 없이 남는다. 배지 문구만 바꾸는 것과 다른 일이다. */
  assert.match(app, /'업체퇴사'/, '폴더 이름이 바뀌었습니다 — 기존 폴더의 명함이 떨어집니다');
});
